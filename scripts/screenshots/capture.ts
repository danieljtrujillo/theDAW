async function snap(page: Page, name: string, clip?: CropRegion): Promise<void> {
  const file = path.join(OUT_DIR, `${name}.png`);
  await page.screenshot({
    path: file,
    fullPage: false,
    clip: clip
      ? { x: clip.x, y: clip.y, width: clip.width, height: clip.height }
      : undefined,
  });
  log(`ok ${name}.png${clip ? ` (${clip.purpose})` : ''}`);
}

async function captureCroppedRegions(page: Page, sceneName: string): Promise<void> {
  const spec = SPEC_BY_SCENE.get(sceneName);
  if (!spec || spec.captureMode === 'full') return;
  for (const crop of spec.cropRegions ?? []) {
    await snap(page, `${sceneName}__${crop.id}`, crop);
  }
}

async function snapScene(page: Page, sceneName: string): Promise<void> {
  await snap(page, sceneName);
  await captureCroppedRegions(page, sceneName);
}

async function writeScreenshotManifest(): Promise<void> {
  const entries = buildScreenshotManifestEntries();
  const jsonFile = path.join(OUT_DIR, 'manifest.json');
  const mdFile = path.join(OUT_DIR, 'manifest.md');
  await fs.writeFile(jsonFile, `${JSON.stringify({ generatedAt: new Date().toISOString(), entries }, null, 2)}\n`, 'utf8');
  const rows = entries.map((entry) => (
    `| \`${entry.file}\` | ${entry.kind} | ${entry.sourceScene} | ${entry.features.map((feature) => `\`${feature}\``).join('<br>')} | ${entry.docsSections.join('<br>')} |`
  )).join('\n');
  await fs.writeFile(
    mdFile,
    `# Screenshot Manifest\n\n` +
      `Generated by \`scripts/screenshots/capture.ts\`. Cropped assets use \`<scene>__<crop-id>.png\` naming and may document several feature IDs at once.\n\n` +
      `| File | Kind | Source scene | Feature IDs | Docs sections |\n` +
      `|---|---|---|---|---|\n` +
      `${rows}\n`,
    'utf8',
  );
  log('ok manifest.json + manifest.md');
}

/**
 * The app shows a fullscreen LoadingScreen overlay (z-200) until the backend
 * health poll succeeds. Every interaction must wait for it to vanish or clicks
 * land on the overlay instead of the actual UI. Also handles the case where the
 * overlay exposes a Skip/Continue button as a safety net.
 */
async function waitForReady(page: Page): Promise<void> {
  const overlay = page.locator('div.fixed.inset-0.z-200').first();
  try {
    await overlay.waitFor({ state: 'hidden', timeout: 25000 });
  } catch {
    const skip = page.getByRole('button', { name: /continue|skip/i }).first();
    if (await skip.isVisible().catch(() => false)) {
      await skip.click();
      await overlay.waitFor({ state: 'hidden', timeout: 5000 });
    }
  }
  await page.waitForTimeout(300);
}

