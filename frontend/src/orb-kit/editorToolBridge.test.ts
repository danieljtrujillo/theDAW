/**
 * The four editor tools that leave the browser, driven against the REAL store
 * with a scripted `fetch`.
 *
 * What is faked is exactly one thing: the HTTP round trip. The clips, the store
 * writes and the arithmetic that turns "make this 125 bpm" into a ratio, or a
 * note's step into a position in an audio file, are the shipping code — those
 * conversions are where this layer can be wrong in a way nobody notices until a
 * part sits 40ms behind a drum take.
 *
 * Run: `npx tsx src/orb-kit/editorToolBridge.test.ts`
 */
import assert from 'node:assert/strict';

import { useEditorStore } from '../state/editorStore';
import type { AudioClip, EditorTrack } from '../state/editorStore';
import type { PianoNote } from '../state/pianoRollStore';
import type { ToolResult } from '../state/editorTools';
import * as bridge from './editorToolBridge';

/* ── harness ─────────────────────────────────────────────────────────────── */

interface Captured {
  url: string;
  form: FormData;
}

let captured: Captured[] = [];

/** A `fetch` that records what it was sent and replies from a script. */
function scripted(reply: (url: string) => Response | Promise<Response>): typeof fetch {
  return (async (input: RequestInfo | URL, init?: RequestInit) => {
    const url = String(input);
    captured.push({ url, form: init?.body as FormData });
    return reply(url);
  }) as unknown as typeof fetch;
}

const jsonReply = (body: unknown, status = 200): Response =>
  new Response(JSON.stringify(body), { status, headers: { 'content-type': 'application/json' } });

const okOf = (r: ToolResult, what: string): ToolResult => {
  assert.ok(r.ok, `${what}: expected ok, got error: ${r.error}`);
  return r;
};
const errOf = (r: ToolResult, what: string): string => {
  assert.ok(!r.ok, `${what}: expected an error, got ok: ${r.message}`);
  return r.error;
};

const blob = (bytes = 8): Blob => new Blob([new Uint8Array(bytes)], { type: 'audio/wav' });

const track = (id: string, name: string): EditorTrack => ({
  id,
  name,
  nameAutoGenerated: false,
  volume: 0.8,
  pan: 0,
  mute: false,
  solo: false,
  color: '#8b5cf6',
});

/** Steps 0, 4 and 8 — at 120 bpm that is 0s, 0.5s and 1.0s into the clip. */
const NOTES = (): PianoNote[] => [
  { id: 'n1', note: 60, step: 0, length: 4, velocity: 100 },
  { id: 'n2', note: 64, step: 4, length: 4, velocity: 100 },
  { id: 'n3', note: 67, step: 8, length: 4, velocity: 100 },
];

