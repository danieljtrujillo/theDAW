/**
 * What `/stretch` really sends back: a RIFF/WAVE file of 32-bit float PCM
 * (`-c:a pcm_f32le`). `withList` puts a LIST chunk between `fmt ` and `data`,
 * which is where ffmpeg writes its encoder tag — a parser that assumes `data`
 * sits at byte 36 reads the LIST chunk as audio.
 */
const f32Wav = (seconds: number, { sampleRate = 8000, channels = 2, withList = false } = {}): Uint8Array<ArrayBuffer> => {
  const frames = Math.round(seconds * sampleRate);
  const dataBytes = frames * channels * 4;
  const list = withList ? 4 + 'ISFTLavf61.1.100\0\0'.length + 8 : 0; // 'INFO' + one ISFT sub-chunk
  const buf = new ArrayBuffer(12 + 24 + (withList ? 8 + list : 0) + 8 + dataBytes);
  const v = new DataView(buf);
  let o = 0;
  const tag = (s: string) => { for (let i = 0; i < 4; i += 1) v.setUint8(o + i, s.charCodeAt(i)); o += 4; };
  tag('RIFF'); v.setUint32(o, buf.byteLength - 8, true); o += 4; tag('WAVE');
  tag('fmt '); v.setUint32(o, 16, true); o += 4;
  v.setUint16(o, 3, true); v.setUint16(o + 2, channels, true); v.setUint32(o + 4, sampleRate, true);
  v.setUint32(o + 8, sampleRate * channels * 4, true); v.setUint16(o + 12, channels * 4, true); v.setUint16(o + 14, 32, true);
  o += 16;
  if (withList) {
    tag('LIST'); v.setUint32(o, list, true); o += 4; tag('INFO');
    tag('ISFT'); v.setUint32(o, 18, true); o += 4;
    for (const ch of 'Lavf61.1.100\0\0\0\0\0\0') { v.setUint8(o, ch.charCodeAt(0)); o += 1; }
  }
  tag('data'); v.setUint32(o, dataBytes, true);
  return new Uint8Array(buf);
};

const wavReply = (bytes: Uint8Array<ArrayBuffer>) => () => new Response(bytes, { status: 200, headers: { 'content-type': 'audio/wav' } });

// The header parser, on its own: the length is read from the file, not assumed.
assert.equal(bridge.wavDurationSec(f32Wav(4).buffer), 4);
assert.equal(bridge.wavDurationSec(f32Wav(2.5, { withList: true, sampleRate: 44100 }).buffer), 2.5);
assert.equal(bridge.wavDurationSec(new Uint8Array(64).buffer), undefined, 'not a WAV at all');
assert.equal(bridge.wavDurationSec(f32Wav(1).buffer.slice(0, 30)), undefined, 'truncated inside fmt');

seed();
const stretchedBytes = f32Wav(4);
const stretched = okOf(
  await bridge.stretchAudioClip({ clip_id: 'a1', target_bpm: 125 }, { fetchImpl: scripted(wavReply(stretchedBytes)) }),
  'stretch',
);
assert.equal(captured[0].url, '/api/editor-tools/stretch');
assert.equal(captured[0].form.get('ratio'), '0.8');
const after = clipOf('a1');
// The WHOLE source came back stretched, so the clip's window into it scales by
// the same ratio and the trim survives: 5 -> 4, 4 -> 3.2, 0.25 -> 0.2.
assert.equal(after.sourceDuration, 4);
assert.equal(after.durationSec, 3.2);
assert.ok(Math.abs(after.offsetIntoSource - 0.2) < 1e-9, `offset ${after.offsetIntoSource}`);
// The source tempo moves with the audio, or the next match computes its ratio
// from a number the blob no longer matches.
assert.equal(after.sourceBpm, 125);
assert.equal(after.mimeType, 'audio/wav');
assert.equal(after.peaks, undefined);
assert.equal(after.audioBlob.size, stretchedBytes.byteLength);
assert.match(stretched.message, /x0\.800/);

// V4-1 — ffmpeg's atempo chain does not land on the sample. When the file comes
// back a few ms SHORT of `old x ratio`, the clip must be sized from the file:
// a window that reads past the end of its media fails to decode at playback.
// This clip's window runs to the very end of its 5s source, so the planned
// window (0.2 .. 4.0) overruns the 3.99s that actually came back.
seed();
useEditorStore.getState().updateClip('a1', { durationSec: 4.75 });
okOf(
  await bridge.stretchAudioClip({ clip_id: 'a1', ratio: 0.8 }, { fetchImpl: scripted(wavReply(f32Wav(3.99))) }),
  'short stretch',
);
const short = clipOf('a1');
assert.ok(Math.abs(short.sourceDuration - 3.99) < 1e-9, `sourceDuration is the file's, got ${short.sourceDuration}`);
assert.ok(Math.abs(short.offsetIntoSource - 0.2) < 1e-9);
assert.ok(
  short.offsetIntoSource + short.durationSec <= short.sourceDuration + 1e-9,
  `window ${short.offsetIntoSource}+${short.durationSec} runs past the ${short.sourceDuration}s source`,
);
assert.ok(Math.abs(short.durationSec - 3.79) < 1e-9, `clamped to the media, got ${short.durationSec}`);

// A body whose length cannot be read is refused — sizing the clip from a guess
// is the bug this replaces.
seed();
assert.match(
  errOf(
    await bridge.stretchAudioClip({ clip_id: 'a1', ratio: 0.8 }, { fetchImpl: scripted(wavReply(new Uint8Array(64))) }),
    'unreadable wav',
  ),
  /not a WAV whose length could be read/,
);
assert.equal(clipOf('a1').sourceDuration, 5, 'untouched after an unreadable reply');

// V4-2 — the request takes seconds; the user keeps working. If the clip's window
// moved while the backend ran, writing `old x ratio` would silently undo their
// edit, so the stretch is refused and their edit stands.
seed();
assert.match(
  errOf(
    await bridge.stretchAudioClip(
      { clip_id: 'a1', ratio: 0.8 },
      {
        fetchImpl: scripted(() => {
          useEditorStore.getState().updateClip('a1', { startSec: 9, durationSec: 1 });
          return wavReply(f32Wav(4))();
        }),
      },
    ),
    'edited mid-stretch',
  ),
  /was edited while the backend was stretching it \(startSec, durationSec changed\); nothing was written/,
);
const kept = clipOf('a1');
assert.equal(kept.startSec, 9, "the user's move stands");
assert.equal(kept.durationSec, 1, "the user's trim stands");
assert.equal(kept.sourceDuration, 5, 'the old audio is still in place');

// An edit that does not touch the window (a rename) is not a conflict — and the
// write is built from the CURRENT record, so the new label survives it.
seed();
okOf(
  await bridge.stretchAudioClip(
    { clip_id: 'a1', ratio: 0.8 },
    {
      fetchImpl: scripted(() => {
        useEditorStore.getState().updateClip('a1', { label: 'renamed while stretching' });
        return wavReply(f32Wav(4))();
      }),
    },
  ),
  'rename mid-stretch',
);
assert.equal(clipOf('a1').label, 'renamed while stretching');
assert.equal(clipOf('a1').sourceDuration, 4);

// A MIDI clip must never take this path — it is re-rendered from its notes.
