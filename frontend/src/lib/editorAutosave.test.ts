/* ── Phase 4: a comped clip's takes survive save → restore ──────────────── */

async function takesAndTheCompSurviveASaveAndRestore(): Promise<void> {
  // A `ClipTake` holds a Blob and a Float32Array. Spreading the live clip into
  // the manifest stringified each take to `{}`, so recovery handed the editor a
  // clip that still claimed to be comped while its takes held no audio at all —
  // `isComped` true, and a non-Blob on its way to decode. Takes go to the same
  // content-addressed asset store the clip's own audio does.
  await drain([owner]);
  const root = new FakeDir(true);
  installGlobals(root, 'grant');
  const mod = await loadAutosave('takes');
  mod.initEditorAutosave();
  await flush();

  const mk = (body: string): Blob => new Blob([body], { type: 'audio/wav' });
  const first = mk('AAAA');
  const active = mk('BBBBBB');
  const takes = [
    { id: 'tk0', label: 'Take 1', audioBlob: first, mimeType: 'audio/wav', sourceDuration: 4, offsetIntoSource: 0, peaks: new Float32Array([1, 0.5]) },
    { id: 'tk1', label: 'Take 2', audioBlob: active, mimeType: 'audio/wav', sourceDuration: 6, offsetIntoSource: 0.5 },
  ];
  st().loadProject({
    tracks: [mkTrack('t1')],
    clips: [
      {
        id: 'c1',
        trackId: 't1',
        label: 'Vocal',
        // The clip's own media IS the active take (the clipComp invariant).
        audioBlob: active,
        mimeType: 'audio/wav',
        startSec: 0,
        durationSec: 5.5,
        sourceDuration: 6,
        offsetIntoSource: 0.5,
        peaks: new Float32Array([0.25]),
        takes,
        comp: [{ startSec: 0, takeIndex: 1 }, { startSec: 2.5, takeIndex: 0, crossfadeSec: 0.02 }],
        activeTakeIndex: 1,
      },
    ] as never,
  });
  mod.flushPendingAutosave();
  await flush(16);

  const dir = saveDirOf(root);
  const manifest = JSON.parse(dir.files.get(MANIFEST)?.body as string) as {
    clips: Array<{ assetHash: string; takes?: Array<{ id: string; assetHash: string; mimeType: string; peaks?: unknown }> }>;
  };
  const stored = manifest.clips[0];
  assert.equal(stored.takes?.length, 2, 'both takes are in the manifest');
  assert.ok(
    stored.takes?.every((t) => typeof t.assetHash === 'string' && t.assetHash.length === 64),
    'each as an asset hash, not as an empty object',
  );
  assert.ok(stored.takes?.every((t) => t.peaks === undefined), 'take peaks are dropped, like the clip’s');
  assert.equal(stored.takes?.[1].assetHash, stored.assetHash, 'the active take and the clip share one asset');

  const assetDir = dir.dirs.get('assets') as FakeDir;
  assert.deepEqual(
    [...assetDir.files.values()].map((f) => f.body).sort(),
    ['AAAA', 'BBBBBB'],
    'both takes’ bytes are on disk — and the GC left the alternate one alone',
  );

  await mod.useAutosaveRecoveryStore.getState().restore();
  const clip = st().clips[0];
  assert.equal(clip.takes?.length, 2, 'the takes came back');
  assert.deepEqual(
    await Promise.all((clip.takes ?? []).map((t) => t.audioBlob.text())),
    ['AAAA', 'BBBBBB'],
    'each holding its own audio',
  );
  assert.ok((clip.takes ?? []).every((t) => t.audioBlob instanceof Blob), 'as real Blobs');
  assert.deepEqual((clip.takes ?? []).map((t) => t.mimeType), ['audio/wav', 'audio/wav']);
  assert.deepEqual((clip.takes ?? []).map((t) => t.label), ['Take 1', 'Take 2']);
  assert.deepEqual((clip.takes ?? []).map((t) => t.sourceDuration), [4, 6]);
  assert.equal(clip.activeTakeIndex, 1);
  assert.equal(clip.audioBlob, clip.takes?.[1].audioBlob, 'clip audio IS the active take, same Blob object');
  assert.deepEqual(clip.comp, [{ startSec: 0, takeIndex: 1 }, { startSec: 2.5, takeIndex: 0, crossfadeSec: 0.02 }]);
  assert.equal(isComped(clip), true, 'and the restored clip is comped, with audio to back it');

  // An asset that is not there costs THIS CLIP its takes, not the user the
  // whole recovery — and the comp goes with them, because a comp indexes takes
  // by position. The clip's own audio is a separate asset and still loads.
  {
    const missing = stored.takes?.[0].assetHash as string;
    assetDir.files.delete(`${missing}.bin`);
    await mod.useAutosaveRecoveryStore.getState().restore();
    const damaged = st().clips[0];
    assert.equal(damaged.takes, undefined, 'no half take list');
    assert.equal(damaged.comp, undefined, 'and no comp indexing into one');
    assert.equal(damaged.activeTakeIndex, undefined);
    assert.equal(await damaged.audioBlob.text(), 'BBBBBB', 'the clip still plays its own audio');
    assert.equal(st().tracks.length, 1, 'and the rest of the session recovered');
  }

  // A clip with no takes restores exactly as it always did.
  st().loadProject({
    tracks: [mkTrack('t1')],
    clips: [
      { id: 'c2', trackId: 't1', label: 'Plain', audioBlob: mk('ZZZ'), mimeType: 'audio/wav', startSec: 0, durationSec: 3, sourceDuration: 3, offsetIntoSource: 0 },
    ] as never,
  });
  mod.flushPendingAutosave();
  await flush(16);
  const plain = JSON.parse(saveDirOf(root).files.get(MANIFEST)?.body as string) as {
    clips: Array<Record<string, unknown>>;
  };
  assert.ok(!('takes' in plain.clips[0]), 'no takes key for a clip that has none');
  await mod.useAutosaveRecoveryStore.getState().restore();
  assert.equal(st().clips[0].takes, undefined);
  assert.equal(isComped(st().clips[0]), false);
  await drain([mod]);
}

