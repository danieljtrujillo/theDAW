async function aMoveThatRefusesAnExistingDestinationStillPromotes(): Promise<void> {
  // If `move()` rejects onto an existing manifest.json and that rejection were
  // allowed to surface, EVERY save after the first would fail and three of them
  // would latch autosave off for the session — silently, because the first save
  // (no destination yet) would look fine.
  const root = new FakeDir(true);
  const dir = await seed(root);
  dir.moveRejectsOnExisting = true;
  installGlobals(root, 'grant');

  st().loadProject({ tracks: [mkTrack('first')], clips: [] });
  owner.flushPendingAutosave();
  await flush(12);
  assert.ok(dir.files.has(MANIFEST), 'the first save lands (no destination to refuse yet)');
  assert.ok(
    dir.ops.includes(`move:${TMP}->${MANIFEST}`),
    'by rename, since there was nothing to overwrite',
  );

  // The second save is the one that exposes the bug.
  st().loadProject({ tracks: [mkTrack('second'), mkTrack('third')], clips: [] });
  owner.flushPendingAutosave();
  await flush(12);

  assert.deepEqual(
    (JSON.parse(dir.files.get(MANIFEST)?.body as string) as { tracks: EditorTrack[] }).tracks.map(
      (t) => t.id,
    ),
    ['second', 'third'],
    'a refused move falls back to copy+drop and the save still completes',
  );
  assert.ok(!dir.files.has(TMP), 'leaving no staging file behind');
  assert.ok(
    dir.ops.includes(`write:${MANIFEST}`),
    'by the copy path — which is the only way manifest.json is written directly',
  );
}

async function aTmpOlderThanTheManifestIsLitterNotDamage(): Promise<void> {
  // A tmp that PARSES but predates the committed manifest is not a torn write:
  // nothing was lost, so it must not be filed as `.corrupt-` or warned about.
  const older = manifestJson(['ancient']);
  const newer = manifestJson(['current1', 'current2']);
  dir1.files.set(TMP, { body: older, mtime: 700 });
  dir1.files.set(MANIFEST, { body: newer, mtime: 800 });

  installGlobals(root1, 'grant');
  await owner.useAutosaveRecoveryStore.getState().restore();

  assert.deepEqual(trackIds(), ['current1', 'current2'], 'the committed manifest wins');
  assert.ok(!dir1.files.has(TMP), 'and the older tmp is taken out of the read path');
  const stale = [...dir1.files.keys()].filter((n) => n.startsWith(`${TMP}.stale-`));
  assert.equal(stale.length, 1, 'filed as stale, not as corrupt');
  assert.equal(dir1.files.get(stale[0])?.body, older, 'with its bytes kept');
  assert.equal(
    [...dir1.files.keys()].filter((n) => n.startsWith(`${TMP}.corrupt-`)).length,
    1,
    'and the earlier torn tmp is still the only corrupt one',
  );
}

/* ── Phase 2: the second tab is recovery-only ───────────────────────────── */

async function aTabThatLosesTheLockNeverWrites(): Promise<void> {
  await drain([owner]);
  const root2 = new FakeDir(true);
  installGlobals(root2, 'deny');

  const observer = await loadAutosave('observer');
  observer.initEditorAutosave();
  await flush();

  assert.equal(observer.autosaveOwnership(), 'observer', 'the lock was already taken');
  assert.equal(observer.useAutosaveRecoveryStore.getState().ownership, 'observer');

  st().loadProject({ tracks: [mkTrack('observed')], clips: [] });
  observer.flushPendingAutosave();
  await flush(12);

  const dir2 = saveDirOf(root2);
  assert.ok(!dir2.files.has(MANIFEST), 'a recovery-only tab writes no manifest');
  assert.ok(!dir2.files.has(TMP), 'and stages nothing either');

  // Recovery-only, not read-only-and-useless: it still restores.
  dir2.files.set(MANIFEST, { body: manifestJson(['ro1', 'ro2']), mtime: 500 });
  dir2.files.set(TMP, { body: '{ truncated', mtime: 600 });
  dir2.ops.length = 0;

  await observer.useAutosaveRecoveryStore.getState().restore();
  assert.deepEqual(trackIds(), ['ro1', 'ro2'], 'the observer can still recover the session');
  assert.ok(dir2.files.has(TMP), 'it leaves even a torn tmp for the owner to resolve');
  assert.deepEqual(dir2.ops, [], 'having performed no OPFS mutation whatsoever');

  await observer.useAutosaveRecoveryStore.getState().discard();
  assert.ok(
    dir2.files.has(MANIFEST),
    'and discarding here cannot delete the owner tab’s autosave',
  );
  assert.equal(observer.useAutosaveRecoveryStore.getState().offer, null, 'the offer still clears');
  return await drain([owner, observer]);
}

/* ── Phase 2b: the lock comes free — the observer takes over ────────────── */

async function anObserverIsPromotedWhenTheLockIsReleased(): Promise<void> {
  // A LONE tab can be told "no" by `ifAvailable`: on a same-tab reload the old
  // document's lock release can land after the new document's request. If the
  // answer were final, that tab would autosave nothing for the rest of the
  // session. It queues an ordinary request instead, which is granted when the
  // previous holder goes away — the reload, or the owner tab being closed.
  await drain([owner]);
  const root = new FakeDir(true);
  const locks = installGlobals(root, 'deny');

  const tab = await loadAutosave('handover');
  tab.initEditorAutosave();
  await flush();

  assert.equal(tab.autosaveOwnership(), 'observer', 'it starts out denied');
  // Startup with NEITHER a manifest nor a tmp: nothing to recover, no crash.
  assert.equal(
    tab.useAutosaveRecoveryStore.getState().offer,
    null,
    'an empty directory offers no recovery',
  );
  assert.equal(saveDirOf(root).files.size, 0, 'and nothing is written on the way past');

  const expected = trackIds();
  locks.grantQueued(); // the previous holder went away
  await flush();

  assert.equal(tab.autosaveOwnership(), 'owner', 'the queued request promotes the tab');
  assert.equal(tab.useAutosaveRecoveryStore.getState().ownership, 'owner', 'in the store too');

  // Nothing touches the document between the handover and this flush, so a
  // manifest here can only come from the save the handover itself scheduled —
  // the edits made while it was an observer were all dropped.
  tab.flushPendingAutosave();
  await flush(12);
  const saved = saveDirOf(root).files.get(MANIFEST)?.body;
  assert.ok(saved, 'the handover scheduled a save of its own rather than waiting for an edit');
  assert.deepEqual(
    (JSON.parse(saved) as { tracks: EditorTrack[] }).tracks.map((t) => t.id),
    expected,
    'and the promoted tab saves the state it could not save before',
  );
  await drain([tab]);
}

