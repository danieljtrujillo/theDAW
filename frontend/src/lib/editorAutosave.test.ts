/** 'grant' = this tab gets the lock, 'deny' = another tab holds it (the
 *  `ifAvailable` callback is handed null), 'none' = no Web Locks at all. */
type LockMode = 'grant' | 'deny' | 'none';

/** Hands back the control the handover test needs: a denied tab QUEUES an
 *  ordinary request behind the holder, and `grantQueued()` is the holder
 *  going away (a closed tab, or the previous document of a reload). */
interface LockControl {
  grantQueued: () => void;
}

function installGlobals(root: FakeDir, lockMode: LockMode): LockControl {
  const queued: ((lock: unknown) => unknown)[] = [];
  const locks =
    lockMode === 'none'
      ? undefined
      : {
          request: (name: string, a: unknown, b?: unknown) => {
            const cb = (typeof a === 'function' ? a : b) as (lock: unknown) => unknown;
            const opts = typeof a === 'function' ? {} : (a as { ifAvailable?: boolean });
            if (opts.ifAvailable) {
              // For 'grant' the callback returns a promise that never settles —
              // the lock is held for the life of the document — so this promise
              // never settles either, exactly like the real LockManager.
              return Promise.resolve(cb(lockMode === 'grant' ? { name, mode: 'exclusive' } : null));
            }
            queued.push(cb);
            return new Promise(() => undefined);
          },
        };
  const control: LockControl = {
    grantQueued: () => {
      for (const cb of queued.splice(0)) void cb({ name: 'thedaw-editor-autosave', mode: 'exclusive' });
    },
  };
  Object.defineProperty(globalThis, 'navigator', {
    value: { storage: { getDirectory: async () => root }, locks },
    configurable: true,
    writable: true,
  });
  Object.defineProperty(globalThis, 'window', {
    value: {
      setTimeout: (fn: () => void, ms: number) => setTimeout(fn, ms) as unknown as number,
      clearTimeout: (h: number) => clearTimeout(h as unknown as NodeJS.Timeout),
      addEventListener: () => undefined,
    },
    configurable: true,
    writable: true,
  });
  return control;
}

type AutosaveModule = typeof import('./editorAutosave.ts');

/** A fresh copy of the module: ownership and the `started` latch are module
 *  state, so one phase per copy. */
const loadAutosave = (tag: string): Promise<AutosaveModule> =>
  import(`./editorAutosave.ts?tab=${tag}`) as Promise<AutosaveModule>;

/** Land every earlier driver's pending debounce somewhere harmless, so a stale
 *  2 s timer cannot write into the root the next phase is about to inspect. */
async function drain(mods: AutosaveModule[]): Promise<void> {
  installGlobals(new FakeDir(true), 'grant');
  for (const m of mods) m.flushPendingAutosave();
  await flush(12);
}

/* ── Phase 0: the project meter round-trips ──────────────────────────────────
   Its own in-memory OPFS and an immediate `window.setTimeout`, so what is
   pinned is the actual debounced save/restore path rather than a
   re-implementation of it — and rather than the explicit `flushPendingAutosave`
   every later phase uses. */

class MeterFakeWritable {
  private chunks: Array<Uint8Array> = [];
  constructor(private readonly onClose: (bytes: Uint8Array) => void) {}
  async write(data: string | Blob | ArrayBuffer | Uint8Array): Promise<void> {
    if (typeof data === 'string') {
      this.chunks.push(new TextEncoder().encode(data));
    } else if (data instanceof Uint8Array) {
      this.chunks.push(data);
    } else if (data instanceof ArrayBuffer) {
      this.chunks.push(new Uint8Array(data));
    } else {
      this.chunks.push(new Uint8Array(await data.arrayBuffer()));
    }
  }
  async close(): Promise<void> {
    const total = this.chunks.reduce((n, c) => n + c.byteLength, 0);
    const out = new Uint8Array(total);
    let at = 0;
    for (const c of this.chunks) {
      out.set(c, at);
      at += c.byteLength;
    }
    this.onClose(out);
  }
}

class MeterFakeFileHandle {
  bytes = new Uint8Array();
  async getFile(): Promise<{ text(): Promise<string>; arrayBuffer(): Promise<ArrayBuffer> }> {
    const bytes = this.bytes;
    return {
      text: async () => new TextDecoder().decode(bytes),
      arrayBuffer: async () => bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength) as ArrayBuffer,
    };
  }
  async createWritable(): Promise<MeterFakeWritable> {
    return new MeterFakeWritable((bytes) => {
      this.bytes = bytes;
    });
  }
}

class MeterFakeDir {
  files = new Map<string, MeterFakeFileHandle>();
  dirs = new Map<string, MeterFakeDir>();
  async getDirectoryHandle(name: string, opts?: { create?: boolean }): Promise<MeterFakeDir> {
    let d = this.dirs.get(name);
    if (!d) {
      if (!opts?.create) throw new Error(`NotFoundError: ${name}`);
      d = new MeterFakeDir();
      this.dirs.set(name, d);
    }
    return d;
  }
  async getFileHandle(name: string, opts?: { create?: boolean }): Promise<MeterFakeFileHandle> {
    let f = this.files.get(name);
    if (!f) {
      if (!opts?.create) throw new Error(`NotFoundError: ${name}`);
      f = new MeterFakeFileHandle();
      this.files.set(name, f);
    }
    return f;
  }
  async removeEntry(name: string, opts?: { recursive?: boolean }): Promise<void> {
    void opts;
    this.files.delete(name);
    this.dirs.delete(name);
  }
  async *keys(): AsyncIterable<string> {
    for (const k of this.files.keys()) yield k;
    for (const k of this.dirs.keys()) yield k;
  }
}

