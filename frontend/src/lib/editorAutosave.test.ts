const root1 = new FakeDir(true);
const dir1 = await seed(root1);
let owner: AutosaveModule;

async function aLeftoverTmpThatParsesIsPromotedOnTheNextStart(): Promise<void> {
  // The previous session staged a manifest and died before the promote. Those
  // bytes are the NEWER, complete document; the committed manifest is a save
  // older than them.
  dir1.files.set(MANIFEST, { body: manifestJson(['old1', 'old2']), mtime: 100 });
  dir1.files.set(TMP, { body: manifestJson(['new1', 'new2', 'new3']), mtime: 200 });

  installGlobals(root1, 'grant');
  owner = await loadAutosave('owner');
  owner.initEditorAutosave();
  await flush();

  assert.equal(owner.autosaveOwnership(), 'owner', 'the first tab takes the lock');
  assert.equal(
    owner.useAutosaveRecoveryStore.getState().ownership,
    'owner',
    'and the store mirrors it for the notice',
  );
  assert.ok(!dir1.files.has(TMP), 'the leftover tmp is promoted, not left to rot');
  assert.deepEqual(
    (JSON.parse(dir1.files.get(MANIFEST)?.body as string) as { tracks: EditorTrack[] }).tracks.map(
      (t) => t.id,
    ),
    ['new1', 'new2', 'new3'],
    'and manifest.json now holds the staged bytes',
  );

  await owner.useAutosaveRecoveryStore.getState().restore();
  assert.deepEqual(trackIds(), ['new1', 'new2', 'new3'], 'so the staged work is what recovers');
}

async function aTornTmpIsSetAsideAndTheCommittedManifestSurvives(): Promise<void> {
  // The crash landed mid-write: the tmp is truncated JSON. The committed
  // manifest predates the failed save and is still whole — it must win, and
  // the evidence must not be deleted.
  const intact = manifestJson(['keep1', 'keep2']);
  const torn = manifestJson(['halfwritten']).slice(0, 40);
  dir1.files.set(MANIFEST, { body: intact, mtime: 300 });
  dir1.files.set(TMP, { body: torn, mtime: 400 });

  await owner.useAutosaveRecoveryStore.getState().restore();

  assert.equal(dir1.files.get(MANIFEST)?.body, intact, 'the committed manifest is byte-identical');
  assert.deepEqual(trackIds(), ['keep1', 'keep2'], 'and it is what recovers');
  assert.ok(!dir1.files.has(TMP), 'the torn tmp is out of the read path');
  const quarantined = [...dir1.files.keys()].filter((n) => n.startsWith(`${TMP}.corrupt-`));
  assert.equal(quarantined.length, 1, 'moved aside exactly once');
  assert.equal(dir1.files.get(quarantined[0])?.body, torn, 'with its bytes kept, never deleted');
}

