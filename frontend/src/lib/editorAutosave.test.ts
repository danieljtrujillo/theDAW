/* ── fake OPFS ───────────────────────────────────────────────────────────────
   Richer than the harness in editorStore.routing.test.ts: it records the order
   of file operations (so "staged, then promoted" is provable rather than
   assumed), carries a modification time (so tmp-vs-manifest recency is
   testable), and can be built with or WITHOUT `move()` — the Chromium-only
   rename — to exercise both promote paths. `moveThrows` is the simulated crash
   between the staging write and the promote. */

interface FakeRecord {
  body: string;
  mtime: number;
}

let clock = 1000;

class FakeDir {
  files = new Map<string, FakeRecord>();
  dirs = new Map<string, FakeDir>();
  ops: string[] = [];
  /** Name whose `close()` is the last thing this "tab" ever does: everything
   *  after it throws. That is what a crash looks like — not a rejected call the
   *  module can recover from, but no further OPFS op landing at all. */
  freezeAfter: string | null = null;
  frozen = false;
  /** An engine whose `move()` refuses to overwrite an existing destination.
   *  Nothing specifies which way Chromium goes, so the module must survive
   *  both — hence this switch rather than an assumption. */
  moveRejectsOnExisting = false;
  constructor(readonly supportsMove: boolean = true) {}

  async getDirectoryHandle(name: string, opts?: { create?: boolean }): Promise<FakeDir> {
    let d = this.dirs.get(name);
    if (!d) {
      if (!opts?.create) throw new Error(`no dir ${name}`);
      d = new FakeDir(this.supportsMove);
      this.dirs.set(name, d);
    }
    return d;
  }

  async getFileHandle(name: string, opts?: { create?: boolean }): Promise<unknown> {
    if (!this.files.has(name)) {
      if (this.frozen) throw new Error('simulated crash: this tab is gone');
      if (!opts?.create) throw new Error(`no file ${name}`);
      clock += 1;
      this.files.set(name, { body: '', mtime: clock });
      this.ops.push(`create:${name}`);
    }
    const dir = this;
    let current = name;
    const handle: Record<string, unknown> = {
      async getFile() {
        const rec = dir.files.get(current);
        if (!rec) throw new Error(`gone ${current}`);
        return {
          lastModified: rec.mtime,
          async text() {
            return rec.body;
          },
          async arrayBuffer() {
            return new TextEncoder().encode(rec.body).buffer;
          },
        };
      },
      async createWritable() {
        let buf = '';
        return {
          async write(data: unknown) {
            // Assets are written as Blobs, the manifest as a string. Both are
            // kept as text here, which is enough for byte-identity checks.
            if (typeof data === 'string') buf += data;
            else if (data instanceof Blob) buf += await data.text();
          },
          async close() {
            if (dir.frozen) throw new Error('simulated crash: this tab is gone');
            clock += 1;
            dir.files.set(current, { body: buf, mtime: clock });
            dir.ops.push(`write:${current}`);
            if (dir.freezeAfter === current) dir.frozen = true;
          },
        };
      },
    };
    if (this.supportsMove) {
      handle.move = async (to: string): Promise<void> => {
        if (dir.frozen) throw new Error('simulated crash: this tab is gone');
        if (dir.moveRejectsOnExisting && dir.files.has(to)) {
          throw new DOMException(`${to} exists`, 'InvalidModificationError');
        }
        const rec = dir.files.get(current);
        if (!rec) throw new Error(`gone ${current}`);
        clock += 1;
        dir.files.delete(current);
        dir.files.set(to, { body: rec.body, mtime: clock });
        dir.ops.push(`move:${current}->${to}`);
        current = to;
      };
    }
    return handle;
  }

  async removeEntry(name: string): Promise<void> {
    if (this.frozen) throw new Error('simulated crash: this tab is gone');
    this.files.delete(name);
    this.dirs.delete(name);
    this.ops.push(`remove:${name}`);
  }

  async *keys(): AsyncIterable<string> {
    for (const k of this.files.keys()) yield k;
  }
}

