async function aCrashDuringThePromoteLeavesTheOldManifestIntact(): Promise<void> {
  const committed = dir1.files.get(MANIFEST)?.body as string;
  // The tab dies the instant the staging write closes: neither promote path
  // gets to run, and nothing else lands either.
  dir1.freezeAfter = TMP;

  st().loadProject({ tracks: [mkTrack('doomed1'), mkTrack('doomed2')], clips: [] });
  owner.flushPendingAutosave();
  await flush(12);

  assert.equal(
    dir1.files.get(MANIFEST)?.body,
    committed,
    'a promote that never completed cannot damage the committed manifest',
  );
  assert.ok(dir1.files.has(TMP), 'the staged bytes are still on disk for the next start');

  // …and the next start — a live directory again — adopts them: that is the
  // whole point of staging.
  dir1.freezeAfter = null;
  dir1.frozen = false;
  await owner.useAutosaveRecoveryStore.getState().restore();
  assert.deepEqual(trackIds(), ['doomed1', 'doomed2'], 'the interrupted save is recovered in full');
  assert.ok(!dir1.files.has(TMP), 'and promoted on the way through');
}

