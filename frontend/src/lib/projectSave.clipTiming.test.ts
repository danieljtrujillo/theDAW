// A saved clip reopens at the speed, the warp and the fade shapes it was saved
// with, and at its own length on the timeline: a clip slowed to half speed is
// twice as long as its source, and reopens that long.
//
// The app's order: the EDIT store holds the session, captureEditorSession
// builds the payload and the embedded files, the JSON comes back as the backend
// returns it, /clip-audio serves the files back, and loadProjectIntoEditor
// opens it.
//
//   cd frontend && npx tsx src/lib/projectSave.clipTiming.test.ts
import assert from 'node:assert/strict';
import { captureEditorSession, loadProjectIntoEditor } from './projectImport.ts';
import type { TasmoProjectLoaded } from './projectClient.ts';
import { useEditorStore, type AudioClip, type EditorTrack } from '../state/editorStore.ts';

// A decoded buffer lasts one second per byte of the blob, so each source has a
// known length.
class FakeAudioContext {
  async decodeAudioData(buf: ArrayBuffer) {
    const seconds = buf.byteLength;
    return { duration: seconds, getChannelData: () => new Float32Array(64).fill(0.5) };
  }
  async close() {}
}
(globalThis as { window?: unknown }).window = { AudioContext: FakeAudioContext };

const track = (id: string): EditorTrack => ({
  id,
  name: id,
  nameAutoGenerated: false,
  volume: 0.8,
  pan: 0,
  mute: false,
  solo: false,
  color: '#fff',
});
const wav = (seconds: number): Blob => new Blob([new Uint8Array(seconds)], { type: 'audio/wav' });
const clip = (id: string, over: Partial<AudioClip>): AudioClip => ({
  id,
  trackId: 't1',
  label: id,
  audioBlob: wav(2),
  mimeType: 'audio/wav',
  sourceDuration: 2,
  offsetIntoSource: 0,
  durationSec: 2,
  startSec: 0,
  color: '#fff',
  ...over,
});

useEditorStore.setState({
  bpm: 120,
  tracks: [track('t1')],
  buses: [],
  clips: [
    // Half speed: two seconds of source across four seconds of timeline.
    clip('slow', { startSec: 1, durationSec: 4, timeStretchRate: 0.5, stretchMode: 'repitch' }),
    // A baked stretch keeps its mode, so it plays its blob at unity.
    clip('baked', { startSec: 6, durationSec: 2, timeStretchRate: 1.25, stretchMode: 'offline' }),
    // Warped: the source's second 1 lands at 1.5 s, and the tail runs on at
    // unity, so the clip is half a second longer than its source.
    clip('warped', {
      startSec: 9,
      durationSec: 2.5,
      warpMarkers: [{ sourceSec: 1, targetSec: 1.5 }],
      fadeInSec: 0.25,
      fadeOutSec: 0.5,
      fadeInCurve: 'exponential',
      fadeOutCurve: 'equal-power',
    }),
    // Nothing set: the payload stays as it was before these fields were saved.
    clip('plain', { startSec: 12, durationSec: 1.5, offsetIntoSource: 0.5 }),
  ],
});

const session = captureEditorSession();
const byId = new Map((session.tracks[0].clips ?? []).map((c) => [c.id, c]));

assert.equal(byId.get('slow')?.time_stretch_rate, 0.5, 'the payload carries the stretch rate');
assert.equal(byId.get('slow')?.stretch_mode, 'repitch', 'and how the stretch is played');
assert.equal(byId.get('baked')?.stretch_mode, 'offline');
assert.deepEqual(byId.get('warped')?.warp_markers, [{ source_sec: 1, target_sec: 1.5 }], 'the payload carries the warp markers');
assert.equal(byId.get('warped')?.fade_in_curve, 'exponential', 'and the fade shapes');
assert.equal(byId.get('warped')?.fade_out_curve, 'equal-power');
const plain = byId.get('plain') ?? {};
for (const key of ['time_stretch_rate', 'stretch_mode', 'warp_markers', 'fade_in_curve', 'fade_out_curve']) {
  assert.equal(key in plain, false, `a clip with no ${key} writes none`);
}

const file = JSON.parse(
  JSON.stringify({ project_name: 'Timing', tempo: session.bpm, sample_rate: 48000, tracks: session.tracks }),
) as TasmoProjectLoaded;

const realFetch = globalThis.fetch;
globalThis.fetch = (async (url: RequestInfo | URL) => {
  const path = decodeURIComponent(String(url).split('path=')[1] ?? '');
  const f = session.files.find((x) => path.endsWith(x.name));
  return f ? new Response(f.blob, { status: 200 }) : new Response('', { status: 404 });
}) as typeof fetch;
try {
  useEditorStore.setState({ tracks: [track('other')], clips: [] });
  await loadProjectIntoEditor(file);
} finally {
  globalThis.fetch = realFetch;
}

const back = new Map(useEditorStore.getState().clips.map((c) => [c.id, c]));
const slow = back.get('slow');
assert.equal(slow?.timeStretchRate, 0.5, 'the slowed clip reopens slowed');
assert.equal(slow?.stretchMode, 'repitch');
assert.equal(slow?.durationSec, 4, 'and as long as it was saved, past the length of its source');
const baked = back.get('baked');
assert.equal(baked?.stretchMode, 'offline', 'a baked stretch reopens baked');
assert.equal(baked?.timeStretchRate, 1.25);
assert.equal(baked?.durationSec, 2);
const warped = back.get('warped');
assert.deepEqual(warped?.warpMarkers, [{ sourceSec: 1, targetSec: 1.5 }], 'the warp markers reopen');
assert.equal(warped?.durationSec, 2.5, 'and the warped clip keeps the length its warp gives it');
assert.equal(warped?.fadeInCurve, 'exponential', 'the fade shapes reopen');
assert.equal(warped?.fadeOutCurve, 'equal-power');
assert.equal(warped?.fadeInSec, 0.25);
assert.equal(warped?.fadeOutSec, 0.5);
const plainBack = back.get('plain');
assert.equal(plainBack?.timeStretchRate, undefined);
assert.equal(plainBack?.stretchMode, undefined);
assert.equal(plainBack?.warpMarkers, undefined);
assert.equal(plainBack?.fadeInCurve, undefined);
assert.equal(plainBack?.durationSec, 1.5, 'an unstretched clip is still held to its source');

// A hand-edited or foreign file: junk values are left out, and an importer's
// warp markers in another shape are not read as theDAW's.
{
  const junk = JSON.parse(JSON.stringify(file)) as TasmoProjectLoaded;
  const c = junk.tracks[0].clips.find((x) => x.id === 'slow')!;
  c.time_stretch_rate = -2;
  c.stretch_mode = 'granular';
  c.fade_in_curve = 'wobbly';
  c.warp_markers = [{ time: 1, content_time: 2 }] as never;
  globalThis.fetch = (async (url: RequestInfo | URL) => {
    const path = decodeURIComponent(String(url).split('path=')[1] ?? '');
    const f = session.files.find((x) => path.endsWith(x.name));
    return f ? new Response(f.blob, { status: 200 }) : new Response('', { status: 404 });
  }) as typeof fetch;
  try {
    await loadProjectIntoEditor(junk);
  } finally {
    globalThis.fetch = realFetch;
  }
  const s = useEditorStore.getState().clips.find((x) => x.id === 'slow');
  assert.equal(s?.timeStretchRate, undefined, 'a rate that is not a positive number is left out');
  assert.equal(s?.stretchMode, undefined, 'a mode the app does not know is left out');
  assert.equal(s?.fadeInCurve, undefined, 'a shape the app does not know is left out');
  assert.equal(s?.warpMarkers, undefined, 'markers in another shape are left out');
  assert.equal(s?.durationSec, 2, 'and the clip is held to its source at unity');
}

console.log('projectSave.clipTiming: ok');
