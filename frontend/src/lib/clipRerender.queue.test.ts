/**
 * The instrument-sync queue (lib/clipRerender createStaleRerenderQueue): one
 * clip at a time, each once, and a request that lands as the queue winds
 * down is still rendered.
 *
 * The case this pins: a render fails, and while the queue handles the
 * failure a clip is handed back in a promise's continuation (as Import as
 * tracks hands back a part whose render failed). The request lands after the
 * queue's last look at its list and before it has finished; a queue that did
 * not look again left the clip waiting until some later request.
 *
 *   cd frontend && npx tsx src/lib/clipRerender.queue.test.ts
 */
import assert from 'node:assert/strict';
import { useEditorStore, type AudioClip, type EditorTrack } from '../state/editorStore.ts';
import { createStaleRerenderQueue, staleMidiClipIds, type ClipRerenderDeps, type StaleRerenderQueue } from './clipRerender.ts';

const ed = () => useEditorStore.getState();
const global = { useSoundfont: true, activeProgram: 7 };
const track = (id: string): EditorTrack => ({ id, name: id, nameAutoGenerated: false, volume: 0.8, pan: 0, mute: false, solo: false, color: '#fff' });
const clip = (id: string): AudioClip => ({
  id,
  trackId: `t-${id}`,
  label: id,
  audioBlob: new Blob([new Uint8Array([1])], { type: 'audio/wav' }),
  mimeType: 'audio/wav',
  sourceDuration: 2,
  offsetIntoSource: 0,
  durationSec: 2,
  startSec: 0,
  color: '#fff',
  sourceKind: 'piano-roll',
  sourcePianoRoll: [{ id: `n-${id}`, note: 60, step: 0, length: 4, velocity: 90, tick: 0, ticks: 960 }],
  sourceBpm: 120,
  sourceTotalSteps: 16,
  // Rendered with program 5; the picker now plays 7, so both are stale.
  renderedProgram: 5,
});

ed().loadProject({ tracks: [track('t-a'), track('t-b')], clips: [clip('a'), clip('b')], bpm: 120 });
assert.deepEqual(staleMidiClipIds(ed().clips, ed().tracks, global), ['a', 'b']);

const rendered: string[] = [];
let queue: StaleRerenderQueue | null = null;
const deps: ClipRerenderDeps = {
  render: async (notes) => {
    const which = ed().clips.find((c) => c.sourcePianoRoll?.[0]?.id === (notes[0] as { id?: string }).id)?.id ?? '?';
    await new Promise((res) => setTimeout(res, 2));
    if (which === 'a') throw new Error('the soundfont refused a');
    rendered.push(which);
    return { blob: new Blob([new Uint8Array([1, 2])], { type: 'audio/wav' }), duration: 2 };
  },
  computePeaks: () => Promise.resolve({ peaks: new Float32Array(4) }),
  global: () => global,
  ensureReady: () => Promise.resolve(),
};
const errors: string[] = [];
queue = createStaleRerenderQueue(deps, (clipId) => {
  errors.push(clipId);
  // A clip handed back in a promise's continuation, after the queue's last look at its list.
  queueMicrotask(() => queue?.request(['b']));
});

queue.request(['a']);
await queue.idle();
assert.deepEqual(errors, ['a'], "a's render failed and was reported");
assert.deepEqual(rendered, ['b'], 'b, requested as the queue wound down, rendered');
assert.deepEqual(queue.pending(), [], 'nothing left waiting');
assert.equal(ed().clips.find((c) => c.id === 'b')?.renderedProgram, 7);

console.log('clipRerender.queue: ok');
