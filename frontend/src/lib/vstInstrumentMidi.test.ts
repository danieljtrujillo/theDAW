/**
 * MIDI stage 4.6: the instrument slot. An EDIT track's MIDI as its VST3
 * instrument plays it (lib/vstInstrumentMidi), the print every bounce makes of
 * it (lib/renderCore printInstrumentTracks), the client that asks the backend
 * for it (lib/vstClient renderInstrumentTrack), and the slot in the store
 * (editorStore setTrackInstrument, freeze and unfreeze).
 *
 *   cd frontend && npx tsx src/lib/vstInstrumentMidi.test.ts
 */
