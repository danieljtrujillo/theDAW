// The EDIT arrangement's tempo map and meter map survive a .tasmo save and
// open, and a file written before the arrangement had maps opens with its one
// tempo and its one meter, as it always did.
//
// Each block replays the app's order: the maps are set through the store's own
// actions, SAVE runs projectStore.save (the transport stubbed at fetch), the
// JSON the backend would store comes back, and loadProjectIntoEditor opens it
// over a session holding other maps.
//
//   cd frontend && npx tsx src/lib/projectImport.timeMap.test.ts
import assert from 'node:assert/strict';
import { loadProjectIntoEditor } from './projectImport.ts';
import type { TasmoProjectLoaded } from './projectClient.ts';
import { useEditorStore, type AudioClip, type EditorTrack } from '../state/editorStore.ts';
import { useProjectStore } from '../state/projectStore.ts';
import { editBarStartSec } from './editTimeMap.ts';

class FakeAudioContext {
  async decodeAudioData() {
    return { duration: 1, getChannelData: () => new Float32Array(64).fill(0.5) };
  }
  async close() {}
}
(globalThis as { window?: unknown }).window = { AudioContext: FakeAudioContext };

const ed = () => useEditorStore.getState();
const track: EditorTrack = { id: 't1', name: 't1', nameAutoGenerated: false, volume: 0.8, pan: 0, mute: false, solo: false, color: '#fff' };
const clip: AudioClip = {
  id: 'a1', trackId: 't1', label: 'a1', audioBlob: new Blob([new Uint8Array([1, 2, 3])], { type: 'audio/wav' }),
  mimeType: 'audio/wav', sourceDuration: 1, offsetIntoSource: 0, durationSec: 1, startSec: 0, color: '#fff', peaks: new Float32Array(0),
};
const beats = () => ed().tempoMap.map((e) => (e.fermata ? [e.beat, 'hold', e.fermata.beats, e.fermata.stretch] : [e.beat, e.bpm, e.curve ?? 'step']));
const meters = () => ed().meterMap.map((s) => [s.bar, s.meter.num, s.meter.den, s.meter.groups.join('+')]);

async function save(): Promise<{ project: TasmoProjectLoaded; files: File[] }> {
  useProjectStore.setState({ projectName: 'Symphony', savePath: 'S.tasmo', pendingTracks: [] });
  let posted: FormData | null = null;
  const realFetch = globalThis.fetch;
  globalThis.fetch = (async (url: RequestInfo | URL, init?: RequestInit) => {
    if (String(url).includes('/api/project/save-session')) {
      posted = init?.body as FormData;
      return new Response(JSON.stringify({ status: 'saved', path: 'S.tasmo', manifest: { audio_mode: 'embedded' } }), { status: 200 });
    }
    return new Response('[]', { status: 200 });
  }) as typeof fetch;
  try {
    await useProjectStore.getState().save();
  } finally {
    globalThis.fetch = realFetch;
  }
  assert.equal(useProjectStore.getState().error, null, 'the save went through');
  const form = posted as FormData | null;
  assert.ok(form, 'SAVE posted to /save-session');
  const project = JSON.parse(await (form.get('project') as Blob).text()) as TasmoProjectLoaded;
  return { project, files: form.getAll('files') as File[] };
}

async function open(project: TasmoProjectLoaded, files: File[]): Promise<void> {
  const realFetch = globalThis.fetch;
  globalThis.fetch = (async (url: RequestInfo | URL) => {
    const path = decodeURIComponent(String(url).split('path=')[1] ?? '');
    const file = files.find((f) => path.endsWith(f.name));
    return file ? new Response(file, { status: 200 }) : new Response('', { status: 404 });
  }) as typeof fetch;
  try {
    await loadProjectIntoEditor(project);
  } finally {
    globalThis.fetch = realFetch;
  }
}

const otherMaps = () => {
  ed().setMeterMap([{ bar: 0, meter: { num: 3, den: 4, groups: [] } }]);
  ed().setTempoMap([{ beat: 0, bpm: 66 }]);
};

// The maps ride the file: 4/4, then 7/8 3+2+2 from bar 5, then 5/4 from bar 9;
// 96 BPM, a ramp from beat 16 down to 72 at beat 30, 132 from beat 40, a fermata at 44.
{
  ed().loadProject({ tracks: [track], clips: [clip], bpm: 96, timeSignature: { num: 4, den: 4 } });
  ed().setMeterAt(4, { num: 7, den: 8, groups: [3, 2, 2] });
  ed().setMeterAt(8, { num: 5, den: 4, groups: [] });
  ed().addTempoEvent({ beat: 16, bpm: 96, curve: 'linear' });
  ed().addTempoEvent({ beat: 30, bpm: 72 });
  ed().addTempoEvent({ beat: 40, bpm: 132 });
  ed().addTempoEvent({ beat: 44, bpm: 132, fermata: { beats: 2, stretch: 3 } });
  const wantBeats = beats();
  const wantMeters = meters();
  const bar12 = editBarStartSec(ed(), 11);

  const { project, files } = await save();
  assert.equal(project.tempo, 96, 'tempo stays the start tempo');
  assert.deepEqual(project.time_signature, [4, 4], 'time_signature stays bar 1\'s meter');
  assert.deepEqual(project.meter_map, [
    { bar: 0, meter: { num: 4, den: 4, groups: [] } },
    { bar: 4, meter: { num: 7, den: 8, groups: [3, 2, 2] } },
    { bar: 8, meter: { num: 5, den: 4, groups: [] } },
  ]);
  assert.deepEqual(project.tempo_map, [
    { beat: 0, bpm: 96 },
    { beat: 16, bpm: 96, curve: 'linear' },
    { beat: 30, bpm: 72 },
    { beat: 40, bpm: 132 },
    { beat: 44, bpm: 132, fermata: { beats: 2, stretch: 3 } },
  ]);

  otherMaps();
  await open(project, files);
  assert.deepEqual(beats(), wantBeats, 'the tempo map reopens');
  assert.deepEqual(meters(), wantMeters, 'the meter map reopens');
  assert.equal(ed().bpm, 96);
  assert.ok(Math.abs(editBarStartSec(ed(), 11) - bar12) < 1e-9, 'bar 12 reopens at the same second');
  assert.equal(ed()._undo.length, 0, 'an open is a fresh document');
}

// A file written before the arrangement had maps: its tempo and time_signature.
{
  const { project, files } = await save();
  const { tempo_map: _t, meter_map: _m, ...older } = project;
  const legacy = { ...older, tempo: 100, time_signature: [7, 8] } as TasmoProjectLoaded;
  otherMaps();
  await open(legacy, files);
  assert.deepEqual(beats(), [[0, 100, 'step']], 'one tempo');
  assert.deepEqual(meters(), [[0, 7, 8, '']], 'one meter');
}

// Junk in the maps falls back to tempo and time_signature rather than to 120 and 4/4.
{
  const { project, files } = await save();
  const junk = {
    ...project,
    tempo: 88,
    time_signature: [5, 4],
    tempo_map: [{ beat: 'x', bpm: 0 }, null],
    meter_map: [{ bar: 0, meter: { num: 0, den: 3, groups: [] } }],
  } as unknown as TasmoProjectLoaded;
  otherMaps();
  await open(junk, files);
  assert.deepEqual(beats(), [[0, 88, 'step']]);
  assert.deepEqual(meters(), [[0, 5, 4, '']]);
}

console.log('projectImport.timeMap: ok');
