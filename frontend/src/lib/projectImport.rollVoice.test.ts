// A saved project reopens with the piano roll on the voice it was left on.
//
// The roll's own voice (pianoRollStore voiceProgram, set from the Vocal2MIDI
// panel's Roll voice select or its assistant) is what an unlinked roll
// auditions and bounces with. Before this, no .tasmo carried it, so a reopened
// project's roll played on whatever program the session before it held.
//
// Each block replays the app's order: the Roll voice is chosen, SAVE runs
// projectStore.save (the transport stubbed at fetch), the JSON the backend
// would store comes back, and loadProjectIntoEditor opens it.
import assert from 'node:assert/strict';
import { applyTasmoRollVoice, loadProjectIntoEditor } from './projectImport.ts';
import { chooseRollVoice } from './rollVoiceChoice.ts';
import type { TasmoProjectLoaded } from './projectClient.ts';
import { useEditorStore, type AudioClip, type EditorTrack } from '../state/editorStore.ts';
import { useProjectStore } from '../state/projectStore.ts';
import { usePianoRollStore } from '../state/pianoRollStore.ts';

class FakeAudioContext {
  async decodeAudioData() {
    return { duration: 1, getChannelData: () => new Float32Array(64).fill(0.5) };
  }
  async close() {}
}
(globalThis as { window?: unknown }).window = { AudioContext: FakeAudioContext };

const track: EditorTrack = { id: 't1', name: 't1', nameAutoGenerated: false, volume: 0.8, pan: 0, mute: false, solo: false, color: '#fff' };
const clip: AudioClip = {
  id: 'a1',
  trackId: 't1',
  label: 'a1',
  audioBlob: new Blob([new Uint8Array([1, 2, 3])], { type: 'audio/wav' }),
  mimeType: 'audio/wav',
  sourceDuration: 1,
  offsetIntoSource: 0,
  durationSec: 1,
  startSec: 0,
  color: '#fff',
  peaks: new Float32Array(0),
};
const roll = () => usePianoRollStore.getState();

/** SAVE, the way the toolbar runs it: returns the project JSON and the files posted. */
async function save(): Promise<{ project: TasmoProjectLoaded; files: File[] }> {
  useEditorStore.setState({ bpm: 120, tracks: [track], clips: [clip] });
  useProjectStore.setState({ projectName: 'Voice', savePath: 'V.tasmo', pendingTracks: [] });
  let posted: FormData | null = null;
  const realFetch = globalThis.fetch;
  globalThis.fetch = (async (url: RequestInfo | URL, init?: RequestInit) => {
    if (String(url).includes('/api/project/save-session')) {
      posted = init?.body as FormData;
      return new Response(JSON.stringify({ status: 'saved', path: 'V.tasmo', manifest: { audio_mode: 'embedded' } }), { status: 200 });
    }
    return new Response('[]', { status: 200 });
  }) as typeof fetch;
  try {
    await useProjectStore.getState().save();
  } finally {
    globalThis.fetch = realFetch;
  }
  assert.equal(useProjectStore.getState().error, null, 'the save went through');
  assert.ok(posted, 'SAVE posted to /save-session');
  const form = posted as FormData;
  const project = JSON.parse(await (form.get('project') as Blob).text()) as TasmoProjectLoaded;
  return { project, files: form.getAll('files') as File[] };
}

async function open(project: TasmoProjectLoaded, files: File[]): Promise<void> {
  const realFetch = globalThis.fetch;
  globalThis.fetch = (async (url: RequestInfo | URL) => {
    const path = decodeURIComponent(String(url).split('path=')[1] ?? '');
    const file = files.find((f) => path.endsWith(f.name));
    return file ? new Response(file, { status: 200 }) : new Response('', { status: 404 });
  }) as typeof fetch;
  try {
    await loadProjectIntoEditor(project);
  } finally {
    globalThis.fetch = realFetch;
  }
}

// The Roll voice is saved, and reopens over a session on another voice.
{
  roll().setEditingClip(null);
  roll().setVoiceProgram(48);
  const { project, files } = await save();
  assert.deepEqual(project.roll_voice, { program: 48 }, 'the file carries the roll voice');
  roll().setVoiceProgram(5);
  await open(project, files);
  assert.equal(roll().voiceProgram, 48, 'the roll reopens on strings');
}

// A roll that follows the picker saves that, and reopening puts a roll on another voice back on the picker.
{
  roll().setVoiceProgram(null);
  const { project, files } = await save();
  assert.deepEqual(project.roll_voice, { program: null });
  roll().setVoiceProgram(33);
  await open(project, files);
  assert.equal(roll().voiceProgram, null, 'the roll follows the picker again');
}

// A file written before the roll voice was saved says nothing: the roll keeps its voice.
{
  roll().setVoiceProgram(48);
  const { project, files } = await save();
  const { roll_voice: _voice, ...older } = project;
  roll().setVoiceProgram(24);
  await open(older as TasmoProjectLoaded, files);
  assert.equal(roll().voiceProgram, 24, 'an older file leaves the roll voice alone');
  // The backend dumps a missing field as null; that too is an older file.
  applyTasmoRollVoice({ roll_voice: null });
  assert.equal(roll().voiceProgram, 24);
}

// Choosing the voice is an edit: the project turns dirty, the roll's undo puts
// the voice before it back, and redo brings the choice again. Opening the
// project sets the voice without either.
{
  roll().setVoiceProgram(0);
  const { project, files } = await save();
  project.roll_voice = { program: 0 };
  await open(project, files);
  assert.equal(roll().voiceProgram, 0);
  assert.equal(useEditorStore.getState().dirty, false, 'a project just opened is clean');
  const depth = roll()._undo.length;

  // The Vocal2MIDI panel's Roll voice select, on an unlinked roll.
  chooseRollVoice(48);
  assert.equal(roll().voiceProgram, 48);
  assert.equal(useEditorStore.getState().dirty, true, 'the roll voice change makes the project dirty');
  assert.equal(roll()._undo.length, depth + 1, 'the choice is one roll undo step');

  roll().undo();
  assert.equal(roll().voiceProgram, 0, 'undo puts Piano back');
  roll().redo();
  assert.equal(roll().voiceProgram, 48, 'redo brings Strings back');

  // A note drawn right after the choice is a step of its own: undoing it keeps the voice.
  roll().addNote({ note: 60, step: 0, length: 4, velocity: 100 });
  roll().undo();
  assert.equal(roll().voiceProgram, 48, 'undoing the note leaves the voice alone');
  roll().undo();
  assert.equal(roll().voiceProgram, 0);

  // Opening the project again records no step and leaves it clean, and the
  // steps already in the history take the opened voice: undoing the note drawn
  // before the open keeps Pad, never the Strings the roll had then.
  roll().redo();
  assert.equal(roll().voiceProgram, 48);
  roll().addNote({ note: 62, step: 4, length: 4, velocity: 100 });
  project.roll_voice = { program: 24 };
  const before = roll()._undo.length;
  await open(project, files);
  assert.equal(roll().voiceProgram, 24);
  assert.equal(roll()._undo.length, before, 'opening records no roll step');
  assert.equal(useEditorStore.getState().dirty, false, 'opening leaves the project clean');
  roll().undo();
  assert.equal(roll().voiceProgram, 24, 'stepping back over the note keeps the opened voice');
  roll().setEditingClip(null);
}

// A hand-edited program outside 0-127 reads as following the picker, as a
// track's does. The backend reads such a file the same way (RollVoice), so the
// project opens; the reader holds the line for a record that reaches it by any
// other route.
{
  roll().setVoiceProgram(24);
  applyTasmoRollVoice({ roll_voice: { program: 200 } });
  assert.equal(roll().voiceProgram, null);
  applyTasmoRollVoice({ roll_voice: { program: 40.5 } });
  assert.equal(roll().voiceProgram, null);
  applyTasmoRollVoice({ roll_voice: { program: 71 } });
  assert.equal(roll().voiceProgram, 71);
}

