// A saved project reopens with each voice in the sound bank it was picked
// from, each track's MIDI output, and the project tuning; a project saved
// before sound banks reopens on the bundled bank at A = 440 (the migration).
//
// The app's order: the EDIT store and the tuning store hold the session,
// captureEditorSession builds the payload (as projectStore does, the document
// half included), the JSON comes back as the backend returns it, and
// loadProjectIntoEditor opens it.
//
//   cd frontend && npx tsx src/lib/projectImport.soundBanks.test.ts
import assert from 'node:assert/strict';
import { captureEditorSession, loadProjectIntoEditor } from './projectImport.ts';
import type { TasmoProjectLoaded } from './projectClient.ts';
import { setBankOffsets, BUNDLED_BANK_ID } from './bankRegistry.ts';
import { clipVoice } from './clipProgram.ts';
import { useEditorStore, type AudioClip, type EditorTrack } from '../state/editorStore.ts';
import { useTuningStore } from '../state/tuningStore.ts';
import { tickOfStep, type PianoNote } from '../state/pianoRollStore.ts';

class FakeAudioContext {
  async decodeAudioData() {
    return { duration: 1, getChannelData: () => new Float32Array(64).fill(0.5) };
  }
  async close() {}
}
(globalThis as { window?: unknown }).window = { AudioContext: FakeAudioContext };

const track = (id: string, extra: Partial<EditorTrack> = {}): EditorTrack => ({
  id,
  name: id,
  nameAutoGenerated: false,
  volume: 0.8,
  pan: 0,
  mute: false,
  solo: false,
  color: '#fff',
  ...extra,
});
const n: PianoNote = { id: 'n0', note: 69, step: 0, length: 4, velocity: 100, tick: tickOfStep(0), ticks: tickOfStep(4) };
const rollClip = (id: string, trackId: string, extra: Partial<AudioClip>): AudioClip => ({
  id,
  trackId,
  label: id,
  audioBlob: null,
  mimeType: 'audio/wav',
  sourceDuration: 1,
  offsetIntoSource: 0,
  durationSec: 1,
  startSec: 0,
  color: '#fff',
  peaks: new Float32Array(0),
  sourceKind: 'piano-roll',
  sourcePianoRoll: [n],
  sourceRollNotes: [n],
  sourceTotalSteps: 16,
  sourceMeterMap: [{ bar: 0, meter: { num: 4, den: 4, groups: [] } }],
  sourcePickupSteps: 0,
  sourceLanes: [{ id: 0, name: 'A', cycleSteps: null }],
  ...extra,
});

const st = () => useEditorStore.getState();
const SF = { useSoundfont: true, activeProgram: 0 };

/** The payload as projectStore saves it, back as the backend returns it. */
function roundTrip(): TasmoProjectLoaded {
  const session = captureEditorSession();
  const payload = { project_name: 'Banks', tempo: session.bpm, tracks: session.tracks, tuning: session.tuning };
  return JSON.parse(JSON.stringify(payload)) as TasmoProjectLoaded;
}

// ── bank ids, MIDI out and tuning survive save -> open ─────────────────────
{
  setBankOffsets([{ id: 'sb-strings0001', offset: 32 }]);
  useTuningStore.getState().setTuning({ referenceHz: 415, temperament: 'werckmeister3', root: 0 });
  useEditorStore.setState({
    bpm: 100,
    tracks: [
      track('t1', {
        instrumentProgram: 40,
        instrumentBank: 1,
        instrumentBankId: 'sb-strings0001',
        midiOut: { id: 'out-1', label: 'loopMIDI Port', channel: 3, clock: true },
        mpeChannels: 6,
      }),
      track('t2', { instrumentProgram: 0, isPercussion: true }),
    ],
    clips: [
      rollClip('c1', 't1', { instrumentProgram: 48, instrumentBank: 0, instrumentBankId: 'sb-strings0001' }),
      rollClip('c2', 't1', {}),
    ],
  });
  const project = roundTrip();
  const t1 = project.tracks.find((t) => t.id === 't1');
  assert.equal(t1?.instrument_bank, 1);
  assert.equal(t1?.instrument_bank_id, 'sb-strings0001');
  assert.deepEqual(t1?.midi_out, { port_id: 'out-1', port_label: 'loopMIDI Port', channel: 3, clock: true });
  assert.equal(t1?.mpe_channels, 6);
  const c1 = t1?.clips.find((c) => c.id === 'c1');
  assert.equal(c1?.instrument_bank_id, 'sb-strings0001');
  assert.equal(t1?.clips.find((c) => c.id === 'c2')?.instrument_bank_id, null, 'a clip with no program names no bank');
  assert.deepEqual(project.tuning, { reference_hz: 415, temperament: 'werckmeister3', root: 0 });

  // Reopen over a different session and a different tuning.
  useTuningStore.getState().setTuning({ referenceHz: 440 });
  useEditorStore.setState({ bpm: 120, tracks: [track('other')], clips: [] });
  await loadProjectIntoEditor(project);
  const t = st().tracks.find((x) => x.id === 't1');
  assert.equal(t?.instrumentBankId, 'sb-strings0001');
  assert.equal(t?.instrumentBank, 1);
  assert.deepEqual(t?.midiOut, { id: 'out-1', label: 'loopMIDI Port', channel: 3, clock: true });
  assert.equal(t?.mpeChannels, 6);
  const clip = st().clips.find((c) => c.id === 'c1');
  assert.equal(clip?.instrumentBankId, 'sb-strings0001');
  assert.deepEqual(clipVoice(clip!, t, SF), { program: 48, percussion: false, bank: 32 }, "the clip plays its bank's preset at the bank's offset");
  assert.deepEqual(clipVoice(st().clips.find((c) => c.id === 'c2')!, t, SF), { program: 40, percussion: false, bank: 33 }, "the other clip plays the track's");
  assert.equal(useTuningStore.getState().tuning.referenceHz, 415, 'the tuning is back');
  assert.equal(useTuningStore.getState().tuning.temperament, 'werckmeister3');
}

// ── the migration: a project from before sound banks ───────────────────────
{
  const old = {
    project_name: 'Old',
    tempo: 120,
    tracks: [
      {
        id: 'p1',
        name: 'Piano',
        type: 'midi',
        instrument_program: 0,
        clips: [
          {
            id: 'k1',
            name: 'k1',
            clip_type: 'midi',
            track_id: 'p1',
            start_time: 0,
            end_time: 1,
            source_kind: 'piano-roll',
            midi_notes: [{ note: 60, step: 0, length: 4, velocity: 100 }],
            instrument_program: 4,
            instrument_bank: 8,
          },
        ],
      },
    ],
  } as unknown as TasmoProjectLoaded;
  useTuningStore.getState().setTuning({ referenceHz: 430 });
  await loadProjectIntoEditor(old);
  const p = st().tracks.find((x) => x.id === 'p1');
  assert.equal(p?.instrumentBankId, undefined, 'the bundled bank');
  assert.equal(p?.midiOut, undefined);
  const k = st().clips.find((c) => c.id === 'k1');
  assert.equal(k?.instrumentBankId, undefined);
  assert.equal(k?.instrumentBank, 8, 'the bundled bank select it was saved with');
  assert.deepEqual(clipVoice(k!, p, SF), { program: 4, percussion: false, bank: 8 });
  assert.equal(useTuningStore.getState().tuning.referenceHz, 440, 'a project with no tuning opens at A = 440');
  assert.equal(BUNDLED_BANK_ID, 'gm');
}

console.log('projectImport.soundBanks: ok');
