// Run with: npx tsx src/components/audio/automationLaneOptions.test.ts — npm test discovers it.
import assert from 'node:assert/strict';
import { buildAddAutomationLaneOptions } from './automationLaneOptions';
import type { AutomationLane, EditorTrack } from '../../state/editorStore';
import type { ChainEntry } from '../../state/effectChainStore';

const track = (id: string, name: string, fxChain: ChainEntry[] = []): EditorTrack => ({
  id,
  name,
  nameAutoGenerated: false,
  volume: 0.8,
  pan: 0,
  mute: false,
  solo: false,
  color: '#fff',
  fxChain,
});

const reverbEntry = (id: string): ChainEntry => ({
  id,
  effect: 'reverb',
  enabled: true,
  params: { decay: 2.0, predelay: 20, tone: 8000, wet: 0.3 },
});

/* ── every AUTOMATION_KINDS shape is offered ─────────────────────────────── */
{
  const t1 = track('t1', 'Drums', [reverbEntry('e1')]);
  const opts = buildAddAutomationLaneOptions([t1], [reverbEntry('m1')], []);

  // trackVolume / trackPan, one each per track.
  assert.ok(opts.some((o) => o.target.kind === 'trackVolume' && o.target.trackId === 't1'), 'offers track volume');
  assert.ok(opts.some((o) => o.target.kind === 'trackPan' && o.target.trackId === 't1'), 'offers track pan');
  assert.ok(
    opts.find((o) => o.target.kind === 'trackVolume')?.label === 'Drums · Volume',
    'volume label names the track',
  );

  // trackFx, one per numeric param on the track's chain entry — using the real
  // rackEffects labels, the same ones laneLabel() reads for an existing lane.
  const decayOpt = opts.find((o) => o.target.kind === 'trackFx' && o.target.paramKey === 'decay');
  assert.ok(decayOpt, 'offers a trackFx target for each param');
  assert.equal(decayOpt!.target.trackId, 't1');
  assert.equal(decayOpt!.target.entryId, 'e1');
  assert.equal(decayOpt!.label, 'Drums · Reverb Decay');
  assert.equal(
    opts.filter((o) => o.target.kind === 'trackFx' && o.target.entryId === 'e1').length,
    4,
    'one option per param on the entry (decay, predelay, tone, wet)',
  );

  // masterFx, same shape, scoped to the master chain instead of a track.
  const masterWet = opts.find((o) => o.target.kind === 'masterFx' && o.target.paramKey === 'wet');
  assert.ok(masterWet, 'offers a masterFx target for each param');
  assert.equal(masterWet!.target.entryId, 'm1');
  assert.equal(masterWet!.label, 'Master · Reverb Mix');
}

/* ── a target that already has a lane is left out ────────────────────────── */
{
  const t1 = track('t1', 'Drums', [reverbEntry('e1')]);
  const existingVolumeLane: AutomationLane = {
    id: 'lane1',
    target: { kind: 'trackVolume', trackId: 't1' },
    points: [],
    enabled: true,
  };
  const existingDecayLane: AutomationLane = {
    id: 'lane2',
    target: { kind: 'trackFx', trackId: 't1', entryId: 'e1', paramKey: 'decay' },
    points: [{ t: 0, v: 1 }],
    enabled: true,
  };

  const opts = buildAddAutomationLaneOptions([t1], [], [existingVolumeLane, existingDecayLane]);

  assert.ok(!opts.some((o) => o.target.kind === 'trackVolume'), 'a lane that exists is not offered again');
  assert.ok(
    !opts.some((o) => o.target.kind === 'trackFx' && o.target.paramKey === 'decay'),
    'an automated FX param is not offered again',
  );
  // Pan and the other three reverb params are untouched, so they still show up.
  assert.ok(opts.some((o) => o.target.kind === 'trackPan'));
  assert.equal(opts.filter((o) => o.target.kind === 'trackFx').length, 3);
}

/* ── no tracks, no master chain: nothing to offer ────────────────────────── */
{
  assert.deepEqual(buildAddAutomationLaneOptions([], [], []), []);
}

/* ── a param with no rack descriptor is never offered (finding 1) ────────── */
// `laneVisual` (WaveformEditor.tsx) returns null, and neither render branch
// draws the lane, when `getRackEffect(entry.effect)` or the param descriptor
// is missing — so a target built from one of these params could never get a
// breakpoint. Both shapes are reachable from `dawDeviceToChainEntry`
// (lib/dawEffectMap.ts) on an imported project.
{
  // A hosted VST3 import: `effect: 'vst3'` never resolves via getRackEffect.
  const vstEntry: ChainEntry = {
    id: 'e-vst',
    effect: 'vst3',
    enabled: true,
    label: 'Ozone 11',
    params: { threshold: -12, mix: 0.5 },
  };
  // A stock effect the DAW importer could not map to a rack id.
  const unmappedEntry: ChainEntry = {
    id: 'e-unmapped',
    effect: 'Ableton Compressor',
    enabled: true,
    params: { ratio: 4 },
  };
  const t1 = track('t1', 'Drums', [unmappedEntry]);

  const opts = buildAddAutomationLaneOptions([t1], [vstEntry], []);

  assert.ok(
    !opts.some((o) => o.target.kind === 'trackFx' && o.target.entryId === 'e-unmapped'),
    'a trackFx param with no rack descriptor is not offered',
  );
  assert.ok(
    !opts.some((o) => o.target.kind === 'masterFx' && o.target.entryId === 'e-vst'),
    'a masterFx param with no rack descriptor is not offered',
  );
  // Volume/Pan are unaffected — they don't go through getRackEffect at all.
  assert.ok(opts.some((o) => o.target.kind === 'trackVolume' && o.target.trackId === 't1'));
  assert.ok(opts.some((o) => o.target.kind === 'trackPan' && o.target.trackId === 't1'));
}

/* ── fxEffectLabel falls back to entry.label (finding 3) ──────────────────── */
// `ChainEntry.label` (effectChainStore.ts) exists for entries with no live
// rack definition — an imported VST3 or unmapped source-DAW effect — and
// should be preferred over the raw `entry.effect` id once such a param IS
// offered (a rack-resolvable param on the same entry, e.g. after mapping).
{
  const labeledEntry: ChainEntry = {
    id: 'e-labeled',
    effect: 'reverb',
    enabled: true,
    label: 'Ozone 11',
    params: { decay: 2.0 },
  };
  const t1 = track('t1', 'Drums', [labeledEntry]);
  const opts = buildAddAutomationLaneOptions([t1], [], []);
  const decayOpt = opts.find((o) => o.target.kind === 'trackFx' && o.target.paramKey === 'decay');
  assert.ok(decayOpt, 'offers the resolvable param');
  // getRackEffect('reverb') has its own label ('Reverb'), which still wins
  // over entry.label — entry.label is only the fallback for an entry with NO
  // rack definition at all.
  assert.equal(decayOpt!.label, 'Drums · Reverb Decay');

  // The `entry.label` half of the fallback chain (an entry with NO rack
  // definition at all) is unreachable through this public API after finding
  // 1's fix: an unresolvable `entry.effect` skips every one of its params, so
  // `fxEffectLabel` is never called for it. `automationLaneOptions.ts` keeps
  // that fallback as deliberate defensive future-proofing rather than dead
  // code to delete — see the comment there. Not re-asserted here: a
  // source-regex pinning an unreachable branch is not a behavioural check.
}

console.log('automationLaneOptions: ok');
