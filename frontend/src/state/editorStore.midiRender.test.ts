/**
 * The editor store's side of a MIDI clip's optional render (lib/midiRender):
 * what a new render does to the clip's render signature, what undo does with
 * a dropped render, and what a frozen master's signature reads from a MIDI
 * clip that holds no render.
 *
 * A frozen master is a render of the whole mix. A MIDI clip with no render
 * plays live and is rendered at export time with the voice it has then, so the
 * signature must move when that voice moves (the clip's program, its track's,
 * a drum track, the picker for a clip with neither) and when its notes move,
 * with no cached audio involved. At 13657cdc the signature read only the
 * clip's audio size, so a track's instrument change on a part with no render
 * left a frozen master reading as current.
 *
 *   cd frontend && npx tsx src/state/editorStore.midiRender.test.ts
 */
import assert from 'node:assert/strict';
import { freezeSignature, trackFreezeSignature, useEditorStore, type AudioClip, type EditorTrack } from './editorStore.ts';
import type { ChainEntry } from './effectChainStore.ts';
import { midiRenderSig } from '../lib/midiRender.ts';
import { clearDecodeCache, decodeCacheStats, decodeClipBlob, peekDecoded } from '../lib/decodeCache.ts';

const ed = () => useEditorStore.getState();
const clipOf = (id: string): AudioClip => ed().clips.find((c) => c.id === id)!;

const track = (over: Partial<EditorTrack> = {}): EditorTrack => ({
  id: 't1', name: 'Horn', nameAutoGenerated: false, volume: 1, pan: 0, mute: false, solo: false, color: '#fff', ...over,
});
const part = (over: Partial<AudioClip> = {}): AudioClip => ({
  id: 'm1', trackId: 't1', label: 'Horn', mimeType: 'audio/wav', sourceDuration: 2, offsetIntoSource: 0, durationSec: 2, startSec: 0, color: '#fff',
  sourceKind: 'piano-roll',
  sourcePianoRoll: [{ id: 'a', note: 65, step: 0, length: 4, velocity: 90 }, { id: 'b', note: 69, step: 4, length: 4, velocity: 90 }],
  sourceBpm: 100,
  sourceTotalSteps: 16,
  ...over,
});
const doc = (clips: AudioClip[], tracks: EditorTrack[], global?: { useSoundfont: boolean; activeProgram: number }) => ({
  clips, tracks, masterFxChain: [] as ChainEntry[], masterVstChain: [] as ChainEntry[], bpm: 100, global,
});

// ── the frozen master's signature follows a live part's voice and notes ─────
{
  const horn = track({ instrumentProgram: 60 });
  const base = freezeSignature(doc([part()], [horn]));
  assert.equal(freezeSignature(doc([part()], [horn])), base, 'the same document signs the same');
  assert.notEqual(freezeSignature(doc([part()], [{ ...horn, instrumentProgram: 61 }])), base, "the track's instrument changed: the export would change");
  assert.notEqual(freezeSignature(doc([part()], [{ ...horn, isPercussion: true }])), base, 'a drum track');
  assert.notEqual(freezeSignature(doc([part({ instrumentProgram: 70 })], [horn])), base, "the clip's own program");
  const moved = part().sourcePianoRoll!.map((n) => (n.id === 'b' ? { ...n, step: 6 } : n));
  assert.notEqual(freezeSignature(doc([part({ sourcePianoRoll: moved })], [horn])), base, 'a note moved');
  assert.notEqual(freezeSignature(doc([part({ sourceBpm: 90 })], [horn])), base, 'its tempo');
  // The picker reaches a part with no program of its own or on its track, and only that part.
  const bare = track();
  const offSig = freezeSignature(doc([part()], [bare], { useSoundfont: false, activeProgram: 0 }));
  assert.notEqual(freezeSignature(doc([part()], [bare], { useSoundfont: true, activeProgram: 48 })), offSig, 'the picker voices a bare part');
  assert.equal(
    freezeSignature(doc([part()], [horn], { useSoundfont: true, activeProgram: 48 })),
    freezeSignature(doc([part()], [horn], { useSoundfont: true, activeProgram: 12 })),
    'but not one whose track holds an instrument',
  );
  assert.equal(freezeSignature(doc([part()], [bare])), offSig, 'a caller that names no picker means soundfonts off');
  // A track stem signs the same way.
  assert.notEqual(trackFreezeSignature({ ...horn, instrumentProgram: 61 }, [part()]), trackFreezeSignature(horn, [part()]));
  assert.notEqual(
    trackFreezeSignature(bare, [part()], { useSoundfont: true, activeProgram: 48 }),
    trackFreezeSignature(bare, [part()], { useSoundfont: false, activeProgram: 0 }),
  );
  // An audio clip is signed as it always was: no MIDI part in its signature.
  const audio: AudioClip = { id: 'a1', trackId: 't1', label: 'a', audioBlob: new Blob([new Uint8Array(4)]), mimeType: 'audio/wav', sourceDuration: 1, offsetIntoSource: 0, durationSec: 1, startSec: 0, color: '#fff' };
  assert.equal(
    freezeSignature(doc([audio], [horn], { useSoundfont: true, activeProgram: 1 })),
    freezeSignature(doc([audio], [horn], { useSoundfont: true, activeProgram: 99 })),
    'the picker does not reach audio',
  );
}

// ── a render's signature travels with the audio it describes ─────────────────
{
  ed().loadProject({ tracks: [track({ instrumentProgram: 60 })], clips: [part()] });
  const rendered = new Blob([new Uint8Array(16)], { type: 'audio/wav' });
  ed().applyClipRender('m1', { audioBlob: rendered, renderedProgram: 60, renderSig: midiRenderSig(clipOf('m1')) });
  assert.equal(clipOf('m1').renderSig, midiRenderSig(clipOf('m1')), 'a render writes what it was made from');
  // New audio that does not say what it was made from is not that render.
  ed().applyClipRender('m1', { audioBlob: new Blob([new Uint8Array(8)], { type: 'audio/wav' }) });
  assert.equal(clipOf('m1').renderSig, undefined, 'so the old signature goes with the old audio');
  // A peak write is not new audio.
  ed().applyClipRender('m1', { audioBlob: rendered, renderSig: 'abc' });
  ed().cachePeaks('m1', new Float32Array(4));
  assert.equal(clipOf('m1').renderSig, 'abc', 'peaks leave the signature alone');
}

// ── dropping a render is one undo step, and undo brings the render back ─────
{
  ed().loadProject({ tracks: [track({ instrumentProgram: 60 })], clips: [part()] });
  const rendered = new Blob([new Uint8Array(16)], { type: 'audio/wav' });
  ed().applyClipRender('m1', { audioBlob: rendered, renderedProgram: 60, renderSig: midiRenderSig(clipOf('m1')) }, new Float32Array(4));
  const steps = ed()._undo.length;
  // "Drop rendered audio" in the clip menu.
  ed().updateClip('m1', { audioBlob: undefined, peaks: undefined, renderSig: undefined, renderedProgram: undefined, renderedPercussion: undefined });
  assert.equal(clipOf('m1').audioBlob, undefined);
  assert.equal(ed()._undo.length, steps + 1, 'one undo step');
  ed().undo();
  assert.equal(clipOf('m1').audioBlob, rendered, 'undo brings the render back');
  assert.equal(clipOf('m1').renderSig, midiRenderSig(clipOf('m1')), 'with its signature');
  assert.equal(clipOf('m1').renderedProgram, 60);
  ed().redo();
  assert.equal(clipOf('m1').audioBlob, undefined, 'and redo drops it again');
}

// ── a replaced or dropped render frees its decoded audio ─────────────────────
{
  const fakeCtx = {
    sampleRate: 44100,
    decodeAudioData: async () => ({ numberOfChannels: 2, length: 44100, sampleRate: 44100, duration: 1, getChannelData: () => new Float32Array(44100) }),
  } as unknown as BaseAudioContext;
  const cached = (blob: Blob) => decodeCacheStats().entries > 0 && peekDecoded(fakeCtx, blob) !== undefined;
  clearDecodeCache();
  ed().loadProject({ tracks: [track({ instrumentProgram: 60 })], clips: [part(), part({ id: 'm2', startSec: 10 })] });
  const first = new Blob([new Uint8Array(16)], { type: 'audio/wav' });
  ed().applyClipRender('m1', { audioBlob: first, renderSig: midiRenderSig(clipOf('m1')) });
  await decodeClipBlob(fakeCtx, first);
  assert.ok(cached(first), 'the render was decoded (an export read it)');
  // A newer render replaces it: the old one's decoded PCM goes.
  const second = new Blob([new Uint8Array(24)], { type: 'audio/wav' });
  ed().applyClipRender('m1', { audioBlob: second, renderSig: midiRenderSig(clipOf('m1')) });
  assert.ok(!cached(first), 'a replaced render is freed');
  await decodeClipBlob(fakeCtx, second);
  // Dropping the render ("Drop rendered audio") frees it too.
  ed().updateClip('m1', { audioBlob: undefined, peaks: undefined, renderSig: undefined, renderedProgram: undefined });
  assert.ok(!cached(second), 'a dropped render is freed');
  // A Blob another clip still plays is kept.
  const shared = new Blob([new Uint8Array(32)], { type: 'audio/wav' });
  ed().applyClipRender('m1', { audioBlob: shared });
  ed().applyClipRender('m2', { audioBlob: shared });
  await decodeClipBlob(fakeCtx, shared);
  ed().updateClip('m1', { audioBlob: undefined });
  assert.ok(cached(shared), 'the other clip still plays it, so it stays decoded');
  // Undo brings a render back (the one the undo step recorded; renders are
  // derived audio and write no step of their own), and its next play decodes it again.
  ed().undo();
  assert.ok(clipOf('m1').audioBlob instanceof Blob);
}

