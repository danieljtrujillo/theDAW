/**
 * The EDIT arrangement's tempo map and meter map in the real editor store:
 * every edit is one undo step, the start tempo and `bpm` never disagree, the
 * tempoStore mirror follows both ways, snap reads both maps, a load brings its
 * maps (or its one tempo and meter), and a MIDI clip's maps are offered and
 * adopted in one undoable step.
 *
 *   cd frontend && npx tsx src/state/editorStore.timeMap.test.ts
 */
import assert from 'node:assert/strict';
import { beginUndoStep, useEditorStore, type AudioClip, type EditorTrack } from './editorStore.ts';
import { useTempoStore } from './tempoStore.ts';
import './editTempoMirror.ts';
import { sanitizeRollTempoMap } from '../lib/rollTempo.ts';
import { editBarStartSec } from '../lib/editTimeMap.ts';

const st = () => useEditorStore.getState();
const beats = () => st().tempoMap.map((e) => [e.beat, e.bpm, e.fermata ? 'hold' : e.curve ?? 'step']);
const meters = () => st().meterMap.map((s) => [s.bar, `${s.meter.num}/${s.meter.den}${s.meter.groups.length ? ` ${s.meter.groups.join('+')}` : ''}`]);
const blob = () => new Blob([new Uint8Array(8)], { type: 'audio/wav' });
const track = (id: string): EditorTrack => ({ id, name: id, nameAutoGenerated: false, volume: 0.8, pan: 0, mute: false, solo: false, color: '#8b5cf6' });
const clip = (id: string, over: Partial<AudioClip> = {}): AudioClip => ({
  id, trackId: 't1', label: id, audioBlob: blob(), mimeType: 'audio/wav', sourceDuration: 8, offsetIntoSource: 0,
  durationSec: 8, startSec: 0, color: '#8b5cf6', ...over,
} as AudioClip);

const fresh = () => {
  st().loadProject({
    tracks: [track('t1')],
    clips: [clip('audio1')],
    bpm: 120,
    timeSignature: { num: 4, den: 4 },
  });
  beginUndoStep();
};

/* ── defaults and the start tempo ────────────────────────────────────────── */
{
  fresh();
  assert.deepEqual(beats(), [[0, 120, 'step']]);
  assert.deepEqual(meters(), [[0, '4/4']]);
  st().addTempoEvent({ beat: 8, bpm: 60 });
  beginUndoStep();
  st().setBpm(90);
  assert.deepEqual(beats(), [[0, 90, 'step'], [8, 60, 'step']], 'the BPM field moves the start, the change stays');
  assert.equal(st().bpm, 90);
  st().removeTempoEvent(0, 'tempo');
  assert.deepEqual(beats()[0], [0, 90, 'step'], 'the start tempo is never removed');
  st().setBpm(Number.NaN);
  assert.equal(st().bpm, 90);
  st().setBpm(900);
  assert.equal(st().bpm, 300, 'the app\'s 20-300 range');
  assert.equal(st().tempoMap[0].bpm, 300);
}

/* ── every tempo and meter edit is an undo step ─────────────────────────── */
{
  fresh();
  const u0 = st()._undo.length;
  st().setMeterAt(2, { num: 7, den: 8, groups: [3, 2, 2] });
  assert.deepEqual(meters(), [[0, '4/4'], [2, '7/8 3+2+2']]);
  assert.equal(st()._undo.length, u0 + 1);
  assert.equal(st().dirty, true, 'a meter edit dirties the document');
  st().setTimeSignature(5, 4);
  assert.deepEqual(meters(), [[0, '5/4'], [2, '7/8 3+2+2']], 'bar 1 changes, the later change stays');
  const u1 = st()._undo.length;
  st().setTimeSignature(5, 4);
  assert.equal(st()._undo.length, u1, 're-picking the meter bar 1 already has is no step');
  st().setMeterAt(3, { num: 7, den: 5, groups: [] });
  assert.equal(st()._undo.length, u1, 'an invalid meter is refused');
  st().addTempoEvent({ beat: 10, bpm: 72, curve: 'linear' });
  st().addTempoEvent({ beat: 20, bpm: 132 });
  st().addTempoEvent({ beat: 24, bpm: 132, fermata: { beats: 2, stretch: 3 } });
  assert.deepEqual(beats(), [[0, 120, 'step'], [10, 72, 'linear'], [20, 132, 'step'], [24, 132, 'hold']]);
  st().undo();
  assert.deepEqual(beats(), [[0, 120, 'step'], [10, 72, 'linear'], [20, 132, 'step']], 'undo takes the fermata back');
  st().undo();
  st().undo();
  assert.deepEqual(beats(), [[0, 120, 'step']]);
  st().undo();
  assert.deepEqual(meters(), [[0, '4/4'], [2, '7/8 3+2+2']], 'undo takes bar 1\'s meter back');
  st().undo();
  assert.deepEqual(meters(), [[0, '4/4']]);
  st().redo();
  st().redo();
  st().redo();
  assert.deepEqual(meters(), [[0, '5/4'], [2, '7/8 3+2+2']]);
  assert.deepEqual(beats(), [[0, 120, 'step'], [10, 72, 'linear']]);
  // Typing a tempo, then its curve, on one event folds into one step.
  beginUndoStep();
  const u2 = st()._undo.length;
  st().moveTempoEvent(10, 'tempo', { bpm: 70 });
  st().moveTempoEvent(10, 'tempo', { bpm: 68 });
  assert.equal(st()._undo.length, u2 + 1, 'a run of edits to one event is one step');
  beginUndoStep();
  st().moveTempoEvent(10, 'tempo', { beat: 12 });
  assert.deepEqual(beats()[1], [12, 68, 'linear'], 'a move keeps its tempo and curve');
  st().undo();
  assert.deepEqual(beats()[1], [10, 68, 'linear']);
  st().removeMeterChange(2);
  assert.deepEqual(meters(), [[0, '5/4']]);
  st().removeMeterChange(0);
  assert.deepEqual(meters(), [[0, '5/4']], 'bar 1 always keeps its meter');
  // A named snapshot carries both maps back.
  st().takeSnapshot('before');
  st().setMeterMap([{ bar: 0, meter: { num: 3, den: 4, groups: [] } }]);
  st().setTempoMap([{ beat: 0, bpm: 66 }]);
  st().restoreSnapshot('before');
  assert.deepEqual(meters(), [[0, '5/4']]);
  assert.deepEqual(beats(), [[0, 120, 'step'], [10, 68, 'linear']]);
}

/* ── tempoStore mirrors the arrangement's map, both ways ────────────────── */
{
  fresh();
  st().addTempoEvent({ beat: 8, bpm: 60, curve: 'linear' });
  st().addTempoEvent({ beat: 12, bpm: 60, fermata: { beats: 1, stretch: 2 } });
  assert.deepEqual(
    useTempoStore.getState().events.map((e) => [e.beat, e.bpm, e.fermata ? 'hold' : e.curve]),
    [[0, 120, 'step'], [8, 60, 'linear'], [12, 60, 'hold']],
    'an arrangement edit reaches tempoStore, fermata included',
  );
  // An edit through tempoStore's own actions comes back as an undoable edit.
  beginUndoStep();
  useTempoStore.getState().insertEvent(16, 150);
  assert.deepEqual(beats(), [[0, 120, 'step'], [8, 60, 'linear'], [12, 60, 'hold'], [16, 150, 'step']]);
  st().undo();
  assert.deepEqual(beats(), [[0, 120, 'step'], [8, 60, 'linear'], [12, 60, 'hold']]);
  assert.deepEqual(useTempoStore.getState().events.map((e) => e.beat), [0, 8, 12], 'and the undo reaches tempoStore');
  // A tempoStore edit that removes the start tempo comes back with a start.
  useTempoStore.getState().setEvents([{ beat: 16, bpm: 174 }]);
  assert.deepEqual(beats(), [[0, 120, 'step'], [16, 174, 'step']]);
  assert.deepEqual(useTempoStore.getState().events.map((e) => [e.beat, e.bpm]), [[0, 120], [16, 174]], 'the two converge');
}

/* ── snap reads both maps ───────────────────────────────────────────────── */
{
  fresh();
  st().setMeterAt(2, { num: 7, den: 8, groups: [3, 2, 2] });
  st().addTempoEvent({ beat: 8, bpm: 60 });
  st().setSnap('1/4');
  assert.ok(Math.abs(st().snapSec(7.3) - 7.5) < 1e-9, 'the 7/8 bar line at 60 BPM, not a straight quarter');
  assert.ok(Math.abs(st().snapSec(5.2) - 5) < 1e-9);
  st().setSnap('1/1');
  assert.ok(Math.abs(st().snapSec(6.1) - 7.5) < 1e-9, 'Bar snaps to the bar lines of the meter map');
  assert.ok(Math.abs(st().snapSec(0.9) - 0) < 1e-9);
  st().setSnap('1/8T');
  assert.ok(Math.abs(st().snapSec(0.18) - 1 / 6) < 1e-9, 'a triplet 8th at 120');
  st().setSnap('off');
  assert.equal(st().snapSec(3.21), 3.21);
}

/* ── a load brings its maps, or its one tempo and meter ─────────────────── */
{
  fresh();
  st().addTempoEvent({ beat: 8, bpm: 60 });
  st().setMeterAt(2, { num: 7, den: 8, groups: [] });
  // A file saved before maps: its bpm and meter, and nothing of the session's changes.
  st().loadProject({ tracks: [track('t1')], clips: [], bpm: 100, timeSignature: { num: 3, den: 4 } });
  assert.deepEqual(beats(), [[0, 100, 'step']]);
  assert.deepEqual(meters(), [[0, '3/4']]);
  assert.equal(st()._undo.length, 0, 'a load is a fresh document');
  // A file with maps: the maps win over its bpm and meter.
  st().loadProject({
    tracks: [track('t1')], clips: [], bpm: 96, timeSignature: { num: 4, den: 4 },
    tempoMap: [{ beat: 0, bpm: 96 }, { beat: 16, bpm: 72, curve: 'linear' }, { beat: 32, bpm: 132 }],
    meterMap: [{ bar: 0, meter: { num: 4, den: 4, groups: [] } }, { bar: 4, meter: { num: 7, den: 8, groups: [3, 2, 2] } }],
  });
  assert.deepEqual(beats(), [[0, 96, 'step'], [16, 72, 'linear'], [32, 132, 'step']]);
  assert.deepEqual(meters(), [[0, '4/4'], [4, '7/8 3+2+2']]);
  assert.equal(st().bpm, 96);
  // New Project (Shell handleNewProject: a load that says nothing) keeps the
  // start tempo and bar 1's meter, as bpm and the time signature always did,
  // and none of the changes that belonged to the bars it cleared. At 13657cdc
  // every meter and tempo change of the old project stayed on the new one.
  st().loadProject({ tracks: [], clips: [] });
  assert.deepEqual(meters(), [[0, '4/4']], 'bar 1\'s meter, no meter change');
  assert.deepEqual(beats(), [[0, 96, 'step']], 'the start tempo, no tempo change');
  assert.equal(st().bpm, 96);
  assert.equal(st()._undo.length, 0);
  // The sequence the review replayed: 96 BPM, 7/8 at bar 5, 5/4 at bar 10, tempo changes at beats 16 and 40.
  st().loadProject({ tracks: [], clips: [], bpm: 96 });
  st().setMeterAt(4, { num: 7, den: 8, groups: [3, 2, 2] });
  st().setMeterAt(9, { num: 5, den: 4, groups: [] });
  st().addTempoEvent({ beat: 16, bpm: 72 });
  st().addTempoEvent({ beat: 40, bpm: 132 });
  st().loadProject({ tracks: [], clips: [] });
  assert.deepEqual(meters(), [[0, '4/4']]);
  assert.deepEqual(beats(), [[0, 96, 'step']]);
  // A session that starts in 7/8 3+2+2 starts the new project in it, groups and all.
  st().setTimeSignature(7, 8);
  st().setMeterAt(0, { num: 7, den: 8, groups: [3, 2, 2] });
  st().setMeterAt(3, { num: 4, den: 4, groups: [] });
  st().loadProject({ tracks: [], clips: [] });
  assert.deepEqual(meters(), [[0, '7/8 3+2+2']]);
}

/* ── a MIDI clip's maps: offered, adopted in one step, kept on refusal ───── */
{
  fresh();
  const tempoMap = sanitizeRollTempoMap([{ beat: 0, bpm: 96 }, { beat: 16, bpm: 72 }], 96);
  st().addClipToTrack({
    ...clip('midi1', { startSec: 0, label: 'Strings' }),
    sourceKind: 'piano-roll', sourceBpm: 96, sourceTempoMap: tempoMap,
    sourceMeterMap: [{ bar: 0, meter: { num: 4, den: 4, groups: [] } }, { bar: 4, meter: { num: 7, den: 8, groups: [3, 2, 2] } }],
    sourcePianoRoll: [{ id: 'n1', note: 60, step: 0, length: 4, velocity: 100 }],
  } as AudioClip & { id: string });
  const id = st().clips.find((c) => c.label === 'Strings')!.id;
  st().offerClipTimeMaps(id);
  assert.deepEqual(st().timeMapOffer, { clipId: id, label: 'Strings', summary: '4/4 then 7/8 3+2+2, 72-96 BPM', anchorSec: 0 });
  // The offer is workspace state: it is not an undo step and does not dirty.
  st().dismissTimeMapOffer();
  assert.equal(st().timeMapOffer, null);
  st().offerClipTimeMaps(id);
  beginUndoStep();
  const u = st()._undo.length;
  const res = st().adoptClipTimeMaps(id);
  assert.deepEqual(res, { ok: true });
  assert.equal(st().timeMapOffer, null, 'adopting clears the offer');
  assert.deepEqual(beats(), [[0, 96, 'step'], [16, 72, 'step']]);
  assert.deepEqual(meters(), [[0, '4/4'], [4, '7/8 3+2+2']]);
  assert.equal(st().bpm, 96);
  assert.equal(st()._undo.length, u + 1, 'tempo and meter together are one step');
  // Bar 6 (the second 7/8 bar) at the clip's own seconds: 4 bars of 4/4 at 96/72 then one 7/8 bar at 72.
  const clipSec = 16 * 60 / 96 + 14 / 4 * 60 / 72;
  assert.ok(Math.abs(editBarStartSec(st(), 5) - clipSec) < 1e-9, 'the arrangement\'s bars are the clip\'s');
  st().undo();
  assert.deepEqual(beats(), [[0, 120, 'step']]);
  assert.deepEqual(meters(), [[0, '4/4']]);
  // Once the arrangement follows the clip, there is nothing to offer.
  st().redo();
  st().offerClipTimeMaps(id);
  assert.equal(st().timeMapOffer, null);
  // An audio clip carries no maps.
  const refused = st().adoptClipTimeMaps('audio1');
  assert.equal(refused.ok, false);
  assert.match(refused.error ?? '', /is audio/);
  assert.equal(st().adoptClipTimeMaps('gone').ok, false);
}

