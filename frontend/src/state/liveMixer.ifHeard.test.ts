/**
 * liveMixer liveMidiIfHeard — which MIDI parts play live when they are heard,
 * the answer EDIT's clip header, its render upkeep and the clip menu read.
 *
 * planLiveMidi (the pass play() makes) skips muted clips, so at 057f7499 a
 * muted violin that plays live read "Silent" with a red dot and "Needs a
 * render to be heard", read "Audio" when it held a kept render, and its menu
 * disabled Drop rendered audio with "no live instrument". Mute decides whether
 * a part sounds, not how: a muted part reads as it plays unmuted, and a muted
 * part that would be past the last live channel still reads as not live.
 *
 *   cd frontend && npx tsx src/state/liveMixer.ifHeard.test.ts
 */
import assert from 'node:assert/strict';
import type { AudioClip, EditorTrack } from './editorStore.ts';
import { liveMidiIfHeard, planLiveMidi } from './liveMixer.ts';
import { midiRenderState, midiRenderStateText } from '../lib/midiRender.ts';

const OFF = { useSoundfont: false, activeProgram: 0 };
const track = (id: string, over: Partial<EditorTrack> = {}): EditorTrack => ({
  id, name: id, nameAutoGenerated: false, volume: 0.8, pan: 0, mute: false, solo: false, color: '#fff', ...over,
});
const part = (id: string, trackId: string, over: Partial<AudioClip> = {}): AudioClip => ({
  id, trackId, label: id, mimeType: 'audio/wav', sourceDuration: 2, offsetIntoSource: 0, durationSec: 2, startSec: 0, color: '#fff',
  sourceKind: 'piano-roll', sourcePianoRoll: [{ id: `${id}n`, note: 60, step: 0, length: 4, velocity: 100 }], sourceTotalSteps: 16,
  ...over,
});

{
  // A muted violin that plays live, and a muted part with no instrument.
  const tracks = [track('vn', { instrumentProgram: 40 }), track('bare')];
  const clips = [part('violin', 'vn', { muted: true }), part('hum', 'bare', { muted: true }), part('violin2', 'vn', { startSec: 4 })];
  const plan = planLiveMidi(clips, tracks, OFF);
  assert.equal(plan.liveClipIds.has('violin'), false, 'the pass skips the muted violin');
  const heard = liveMidiIfHeard(clips, tracks, OFF);
  assert.ok(heard.has('violin'), 'it plays live when heard');
  assert.ok(heard.has('violin2'), 'the unmuted violin as the pass has it');
  assert.equal(heard.has('hum'), false, 'a part with no instrument cannot play live, muted or not');
  // The words its header and menu show: live, with no render.
  const state = midiRenderState(clips[0], tracks[0], OFF);
  assert.equal(state, 'none');
  assert.equal(midiRenderStateText(state, heard.has('violin')), 'Plays live; renders when exported', 'not "Needs a render to be heard"');
  // Unmuting changes nothing about how it plays.
  const unmuted = clips.map((c) => (c.id === 'violin' ? { ...c, muted: false } : c));
  assert.deepEqual([...liveMidiIfHeard(unmuted, tracks, OFF)].sort(), [...heard].sort());
}

{
  // Eight drum tracks take the eight drum channels. A ninth, muted, would be
  // past the last one when heard, so it reads as not live; the same part muted
  // on the first drum track would take its channel, so it reads live.
  const drums = Array.from({ length: 9 }, (_, i) => track(`d${i}`, { isPercussion: true }));
  const last = drums.map((t, i) => part(`k${i}`, t.id, i === 8 ? { muted: true } : {}));
  const heardLast = liveMidiIfHeard(last, drums, OFF);
  assert.equal(heardLast.has('k8'), false, 'past the last drum channel when heard');
  for (let i = 0; i < 8; i += 1) assert.ok(heardLast.has(`k${i}`), `drum track ${i} keeps its channel`);
  const first = drums.map((t, i) => part(`k${i}`, t.id, i === 0 ? { muted: true } : {}));
  const heardFirst = liveMidiIfHeard(first, drums, OFF);
  assert.ok(heardFirst.has('k0'), 'the first drum track would take the first drum channel');
  // The unmuted parts read as the pass plays them: the ninth has a channel while the first is muted.
  const pass = planLiveMidi(first, drums, OFF);
  for (let i = 1; i < 9; i += 1) assert.equal(heardFirst.has(`k${i}`), pass.liveClipIds.has(`k${i}`), `drum track ${i} as the pass has it`);
}

console.log('liveMixer.ifHeard: ok');
