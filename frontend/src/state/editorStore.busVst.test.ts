// A bus takes VST3 inserts, and a lane can ride a hosted plugin's parameter on
// a track, a bus or the master (state/editorStore).
//
// The bus rack had add / remove / bypass / params and nothing else: no way to
// put a VST3 on it, move one, or keep what its editor dialled in. A busFx lane
// did not exist, and a lane on a master VST3 resolved nothing: the store looked
// for its entry in the master RACK only, so a write pass seeded it from the
// lane instead of from what the plugin was actually set to. These cases replay
// the store calls the mixer's bus rack, the plugin windows and a record pass
// make, and read the document back.
//
// Run: npx tsx src/state/editorStore.busVst.test.ts
import assert from 'node:assert/strict';

import {
  automationEntryFor, automationTargetKey, beginUndoStep, useEditorStore,
  type AutomationLane, type AutomationTarget, type EditorBus, type EditorTrack,
} from './editorStore.ts';
import type { ChainEntry } from './effectChainStore.ts';

const st = () => useEditorStore.getState();

const track = (over: Partial<EditorTrack> = {}): EditorTrack => ({
  id: 't1', name: 'T1', nameAutoGenerated: false, volume: 0.8, pan: 0,
  mute: false, solo: false, color: '#fff', ...over,
});

const vst = (id: string, params: Record<string, number> = {}): ChainEntry => ({
  id, effect: 'vst3', enabled: true, params, vst: { plugin_path: `C:/Plugins/${id}.vst3`, plugin_name: id },
});

const bus = (over: Partial<EditorBus> & { id: string }): EditorBus => ({
  name: over.id.toUpperCase(), fxChain: [], volume: 0.8, mute: false, ...over,
});

const lane = (target: AutomationTarget, points: AutomationLane['points']): AutomationLane =>
  ({ id: `lane-${automationTargetKey(target)}`, target, points, enabled: true });

const reset = (over: Record<string, unknown> = {}): void => {
  useEditorStore.setState({
    tracks: [track()],
    clips: [],
    buses: [],
    masterFxChain: [],
    masterVstChain: [],
    automationLanes: [],
    automationHolds: {},
    automationMode: 'read',
    ...over,
  } as never);
  useEditorStore.setState({ _undo: [], _redo: [] });
  beginUndoStep();
};

const busChain = (id: string): ChainEntry[] => st().buses.find((b) => b.id === id)?.fxChain ?? [];

/* ── 1. The bus rack takes a VST3 and keeps what it is set to ─────────────── */

{
  reset({ buses: [bus({ id: 'b1' })] });
  st().addBusEffect('b1', 'reverb');
  st().addBusVst('b1', { plugin_path: 'C:/Plugins/Vital.vst3', plugin_name: 'Vital' });
  const [rack, plugin] = busChain('b1');
  assert.equal(rack.effect, 'reverb');
  assert.equal(plugin.effect, 'vst3', 'the plugin is a hosted insert on the bus');
  assert.deepEqual(plugin.vst, { plugin_path: 'C:/Plugins/Vital.vst3', plugin_name: 'Vital' });
  assert.equal(plugin.enabled, true);

  st().reorderBusEffect('b1', 1, 0);
  assert.deepEqual(busChain('b1').map((e) => e.effect), ['vst3', 'reverb'], 'the plugin moved ahead of the reverb');
  st().reorderBusEffect('b1', 0, 5);
  assert.deepEqual(busChain('b1').map((e) => e.effect), ['vst3', 'reverb'], 'a move past the end changes nothing');

  st().toggleBusEffect('b1', plugin.id);
  assert.equal(busChain('b1')[0].enabled, false, 'bypass');

  // The plugin's own editor hands its state back through the bus's sink.
  st().setBusVstRawState('b1', plugin.id, 'c3RhdGU=', 'thedaw');
  assert.equal(busChain('b1')[0].vst?.raw_state, 'c3RhdGU=');
  assert.equal(busChain('b1')[0].vst?.state_host, 'thedaw');

  st().removeBusEffect('b1', plugin.id);
  assert.deepEqual(busChain('b1').map((e) => e.effect), ['reverb']);
}

/* ── 2. A master VST3 can be bypassed, and its lanes go with it ───────────── */

{
  const m = vst('mv', { p0: 0.4 });
  const target: AutomationTarget = { kind: 'masterFx', entryId: 'mv', paramKey: 'p0' };
  reset({ masterVstChain: [m], automationLanes: [lane(target, [{ t: 0, v: 0.9 }])] });
  st().toggleMasterVst('mv');
  assert.equal(st().masterVstChain[0].enabled, false, 'a master plugin has a bypass of its own now');
  st().toggleMasterVst('mv');
  assert.equal(st().masterVstChain[0].enabled, true);
  st().removeMasterVst('mv');
  assert.deepEqual(st().automationLanes, [], 'a lane on a removed master plugin writes to nothing, so it goes');
}

/* ── 3. Every FX lane finds its insert, wherever the insert sits ───────────── */

{
  const tv = vst('tv', { p1: 0.3 });
  const bv = vst('bv', { p3: 0.7 });
  const mv = vst('mv', { p0: 0.4 });
  reset({ tracks: [track({ fxChain: [tv] })], buses: [bus({ id: 'b1', fxChain: [bv] })], masterVstChain: [mv] });
  const s = st();
  assert.equal(automationEntryFor(s, { kind: 'trackFx', trackId: 't1', entryId: 'tv', paramKey: 'p1' }), tv);
  assert.equal(automationEntryFor(s, { kind: 'busFx', trackId: 'b1', entryId: 'bv', paramKey: 'p3' }), bv);
  assert.equal(automationEntryFor(s, { kind: 'masterFx', entryId: 'mv', paramKey: 'p0' }), mv);
  assert.equal(automationEntryFor(s, { kind: 'busFx', trackId: 't1', entryId: 'bv', paramKey: 'p3' }), undefined,
    'a bus lane names its bus, not a track');
}

/* ── 4. A write pass records what the plugin is SET to ────────────────────── */

// `write` seeds every enabled lane with the stored control value, because a
// write pass records what is heard. For a bus plugin and a master plugin the
// store used to find no stored value and seed from the lane: the pass then
// wrote the lane's old curve over itself instead of the plugin's setting.
{
  const bv = vst('bv', { p3: 0.7 });
  const mv = vst('mv', { p0: 0.4 });
  const busTarget: AutomationTarget = { kind: 'busFx', trackId: 'b1', entryId: 'bv', paramKey: 'p3' };
  const masterTarget: AutomationTarget = { kind: 'masterFx', entryId: 'mv', paramKey: 'p0' };
  reset({
    buses: [bus({ id: 'b1', fxChain: [bv] })],
    masterVstChain: [mv],
    automationLanes: [lane(busTarget, [{ t: 0, v: 0.2 }]), lane(masterTarget, [{ t: 0, v: 0.9 }])],
  });
  st().setAutomationMode('write');
  st().beginAutomationPass(5);
  const holds = st().automationHolds;
  assert.equal(holds[automationTargetKey(busTarget)]?.value, 0.7, 'the bus plugin is held at its own setting');
  assert.equal(holds[automationTargetKey(masterTarget)]?.value, 0.4, 'the master plugin is held at its own setting');
  st().endAutomationPass();
}

/* ── 5. A bus's lanes go when the bus does ─────────────────────────────────── */

{
  const busTarget: AutomationTarget = { kind: 'busFx', trackId: 'b1', entryId: 'bv', paramKey: 'p3' };
  reset({ buses: [bus({ id: 'b1', fxChain: [vst('bv')] })], automationLanes: [lane(busTarget, [{ t: 0, v: 0.2 }])] });
  st().removeBus('b1');
  assert.deepEqual(st().automationLanes, [], 'removing the bus removes the lanes on its inserts');
}

console.log('editorStore.busVst: all passed');
