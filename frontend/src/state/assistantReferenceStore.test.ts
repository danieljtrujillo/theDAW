import assert from 'node:assert/strict';

import { useEditorStore, type AudioClip, type EditorTrack } from './editorStore.ts';
import { useLibraryStore, type LibraryEntry } from './libraryStore.ts';
import { useProjectStore } from './projectStore.ts';
import {
  referenceContextEntry,
  referenceForClip,
  referenceForLibraryEntry,
  referenceForTimeSelection,
  referenceForTrack,
  referenceKey,
  resolveAssistantReference,
  useAssistantReferenceStore,
  type AssistantReference,
} from './assistantReferenceStore.ts';

// References are the "act on THIS" list the user hands gantasmob0t. They carry
// ids and a display label — never bytes, never a blob URL, never a path — and
// a reference whose target is gone is reported missing rather than quietly
// re-aimed at whatever happens to be selected now.

const ed = () => useEditorStore.getState();
const refs = () => useAssistantReferenceStore.getState();

const mkTrack = (id: string, name = id): EditorTrack => ({
  id, name, nameAutoGenerated: false, volume: 0.8, pan: 0, mute: false, solo: false, color: '#fff',
});

const mkClip = (id: string, trackId: string, over: Partial<AudioClip> = {}): AudioClip =>
  ({
    id,
    trackId,
    label: id.toUpperCase(),
    audioBlob: new Blob(['0123']),
    mimeType: 'audio/wav',
    sourceDuration: 8,
    offsetIntoSource: 0,
    durationSec: 4,
    startSec: 2,
    color: '#fff',
    ...over,
  }) as AudioClip;

const mkEntry = (id: string, title: string): LibraryEntry =>
  ({
    id,
    title,
    prompt: '',
    negativePrompt: '',
    model: 'medium',
    duration: 10,
    steps: 8,
    cfg: 1,
    seed: 1,
    audioUrl: `/api/library/audio/${id}`,
    audioFilename: `${id}.wav`,
    fileSizeBytes: 10,
    mimeType: 'audio/wav',
    timestamp: '2026-01-01T00:00:00Z',
    favorite: false,
    rating: null,
    tags: [],
    notes: '',
    lyrics: '',
    source: 'generate',
  }) as LibraryEntry;

/** A fresh arrangement: tracks a/b, clips c1 (on a, from library entry e1) and c2 (on b). */
const fresh = (): void => {
  useAssistantReferenceStore.getState().clear();
  useProjectStore.setState({ projectName: 'Demo Set' });
  useLibraryStore.setState({ entries: [mkEntry('e1', 'Kick Loop'), mkEntry('e2', 'Pad')] });
  ed().loadProject({
    tracks: [mkTrack('a', 'Drums'), mkTrack('b', 'Bass')],
    clips: [
      mkClip('c1', 'a', { libraryEntryId: 'e1', gain: 0.5, muted: true }),
      mkClip('c2', 'b'),
    ],
  });
};

// ── Helpers build id-first references, and nothing else ────────────────────
{
  fresh();
  const clipRef = referenceForClip('c1');
  assert.ok(clipRef && clipRef.kind === 'clip');
  assert.equal(clipRef.clipId, 'c1');
  assert.equal(clipRef.trackId, 'a');
  assert.equal(clipRef.assetId, 'e1');
  assert.equal(clipRef.projectId, 'Demo Set');
  assert.equal(clipRef.label, 'C1');
  assert.ok(Number.isFinite(clipRef.addedAt));

  assert.equal(referenceForClip('nope'), null, 'an unknown clip id yields no reference');

  const trackRef = referenceForTrack('b');
  assert.deepEqual(trackRef, { kind: 'track', trackId: 'b', label: 'Bass' });
  assert.equal(referenceForTrack('zz'), null);

  const assetRef = referenceForLibraryEntry('e2');
  assert.deepEqual(assetRef, { kind: 'library-asset', entryId: 'e2', label: 'Pad' });
  assert.equal(referenceForLibraryEntry('e9'), null);

  assert.equal(referenceForTimeSelection(), null, 'no selection, no range reference');
}

// ── A range reference comes from the editor's own time selection ───────────
{
  fresh();
  ed().setTimeSelection({ startSec: 1.5, endSec: 4, scope: { kind: 'all-tracks' } });
  const all = referenceForTimeSelection();
  assert.ok(all && all.kind === 'time-range');
  assert.equal(all.startSec, 1.5);
  assert.equal(all.endSec, 4);
  assert.equal(all.trackIds, 'all');
  assert.equal(all.label, '1.50s–4.00s (all tracks)');

  ed().setTimeSelection({ startSec: 0, endSec: 2, scope: { kind: 'tracks', ids: ['a'] } });
  const scoped = referenceForTimeSelection();
  assert.ok(scoped && scoped.kind === 'time-range');
  assert.deepEqual(scoped.trackIds, ['a']);
  assert.equal(scoped.label, '0.00s–2.00s (1 track)');
}

// ── Serialized references carry no bytes, blob URLs or absolute paths ──────
{
  fresh();
  ed().setTimeSelection({ startSec: 0, endSec: 2, scope: { kind: 'all-tracks' } });
  refs().add(referenceForClip('c1')!);
  refs().add(referenceForTimeSelection()!);
  refs().add(referenceForLibraryEntry('e1')!);
  refs().add(referenceForTrack('a')!);

  const wire = JSON.stringify(refs().references);
  assert.equal(refs().references.length, 4);
  assert.ok(!wire.includes('blob:'), 'no blob URLs');
  assert.ok(!/audioBlob|audioUrl|mediaUrl|peaks/.test(wire), 'no bytes or media URLs');
  assert.ok(!/[A-Za-z]:\\|\/api\/|(^|[^\w])\/(home|Users)\//.test(wire), 'no paths');
}

// ── add() dedupes by identity; remove()/clear() take the chips back off ────
{
  fresh();
  ed().setTimeSelection({ startSec: 1, endSec: 3, scope: { kind: 'all-tracks' } });
  const clipRef = referenceForClip('c1')!;
  const rangeRef = referenceForTimeSelection()!;
  const assetRef = referenceForLibraryEntry('e1')!;

  refs().add(clipRef);
  refs().add(referenceForClip('c1')!); // same clip, freshly built
  refs().add(rangeRef);
  refs().add({ ...rangeRef }); // same bounds and scope
  refs().add(assetRef);
  refs().add(referenceForLibraryEntry('e1')!);
  assert.equal(refs().references.length, 3, 'same clip / same range / same entry collapse');

  // Same bounds over a different scope is a DIFFERENT range.
  refs().add({ kind: 'time-range', startSec: 1, endSec: 3, trackIds: ['a'], label: 'a only' });
  assert.equal(refs().references.length, 4);
  // Track order within a scope does not create a new identity.
  refs().add({ kind: 'time-range', startSec: 1, endSec: 3, trackIds: ['a'], label: 'dup' });
  assert.equal(refs().references.length, 4);

  refs().remove(referenceKey(clipRef));
  assert.equal(refs().references.length, 3);
  assert.ok(!refs().references.some((r) => referenceKey(r) === referenceKey(clipRef)));
  refs().remove('nothing-like-this');
  assert.equal(refs().references.length, 3, 'removing an unknown key is a no-op');

  refs().clear();
  assert.deepEqual(refs().references, []);
}

// ── A malformed range is refused rather than stored ────────────────────────
{
  fresh();
  for (const [startSec, endSec] of [[NaN, 2], [0, Infinity], [3, 1], [2, 2]]) {
    assert.throws(
      () => refs().add({ kind: 'time-range', startSec, endSec, trackIds: 'all', label: 'bad' }),
      RangeError,
      `[${startSec}, ${endSec}) is refused`,
    );
  }
  assert.deepEqual(refs().references, [], 'nothing malformed reaches the list');
}

// ── resolve(): ok / changed / missing against the live document ────────────
{
  fresh();
  const clipRef = referenceForClip('c1')!;
  assert.deepEqual(resolveAssistantReference(clipRef), { status: 'ok', detail: 'Clip "C1" on Drums' });
  assert.equal(refs().resolve(clipRef).status, 'ok', 'the store method matches the pure one');

  // Moved to another track: still there, but not what the user pointed at.
  ed().updateClip('c1', { trackId: 'b' });
  const moved = resolveAssistantReference(clipRef);
  assert.equal(moved.status, 'changed');
  assert.match(moved.detail, /moved to Bass/);

  // Renamed: also a change the model must see.
  ed().updateClip('c1', { trackId: 'a', label: 'C1 edit' });
  const renamed = resolveAssistantReference(clipRef);
  assert.equal(renamed.status, 'changed');
  assert.match(renamed.detail, /renamed to "C1 edit"/);

  // Deleted: missing, never retargeted onto the current selection.
  ed().removeClip('c1');
  ed().setSelected('c2');
  const gone = resolveAssistantReference(clipRef);
  assert.equal(gone.status, 'missing');
  assert.match(gone.detail, /no longer in the project/);
}

{
  fresh();
  const assetRef = referenceForLibraryEntry('e1')!;
  assert.equal(resolveAssistantReference(assetRef).status, 'ok');
  useLibraryStore.setState({ entries: [mkEntry('e1', 'Kick Loop v2'), mkEntry('e2', 'Pad')] });
  const retitled = resolveAssistantReference(assetRef);
  assert.equal(retitled.status, 'changed');
  assert.match(retitled.detail, /Kick Loop v2/);
  useLibraryStore.setState({ entries: [mkEntry('e2', 'Pad')] });
  assert.equal(resolveAssistantReference(assetRef).status, 'missing');

  const trackRef = referenceForTrack('a')!;
  assert.equal(resolveAssistantReference(trackRef).status, 'ok');
  ed().updateTrack('a', { name: 'Drum Bus' });
  assert.equal(resolveAssistantReference(trackRef).status, 'changed');
  ed().removeTrack('a');
  assert.equal(resolveAssistantReference(trackRef).status, 'missing');
}

{
  fresh();
  const allRange: AssistantReference = {
    kind: 'time-range', startSec: 0, endSec: 2, trackIds: 'all', label: 'intro',
  };
  assert.equal(resolveAssistantReference(allRange).status, 'ok');

  const scoped: AssistantReference = {
    kind: 'time-range', startSec: 0, endSec: 2, trackIds: ['a', 'b'], label: 'intro',
  };
  assert.equal(resolveAssistantReference(scoped).status, 'ok');
  ed().removeTrack('b');
  const partial = resolveAssistantReference(scoped);
  assert.equal(partial.status, 'changed', 'one of the two scoped tracks is gone');
  assert.match(partial.detail, /b/);
  ed().removeTrack('a');
  assert.equal(resolveAssistantReference(scoped).status, 'missing', 'every scoped track is gone');
}

// ── The app-context entry carries current facts, and flags a missing one ───
{
  fresh();
  const clipRef = referenceForClip('c1')!;
  const live = referenceContextEntry(clipRef);
  assert.equal(live.kind, 'clip');
  assert.equal(live.status, 'ok');
  assert.deepEqual(live.clip, {
    id: 'c1', trackId: 'a', startSec: 2, durationSec: 4, gain: 0.5, muted: true,
  });

  // Defaults are reported explicitly so the model never has to assume them.
  assert.deepEqual(referenceContextEntry(referenceForClip('c2')!).clip, {
    id: 'c2', trackId: 'b', startSec: 2, durationSec: 4, gain: 1, muted: false,
  });

  ed().removeClip('c1');
  const dead = referenceContextEntry(clipRef);
  assert.equal(dead.status, 'missing');
  assert.equal(dead.clip, undefined, 'a missing clip reports no facts to act on');
  assert.equal(dead.clipId, 'c1', 'the id the user pointed at is still named');

  const rangeEntry = referenceContextEntry({
    kind: 'time-range', startSec: 1.234, endSec: 4.567, trackIds: ['b'], label: 'hook',
  });
  assert.equal(rangeEntry.status, 'ok');
  assert.deepEqual(rangeEntry.range, { startSec: 1.23, endSec: 4.57, trackIds: ['b'] });

  assert.deepEqual(referenceContextEntry(referenceForLibraryEntry('e1')!).asset, {
    entryId: 'e1', title: 'Kick Loop',
  });
  assert.deepEqual(referenceContextEntry(referenceForTrack('b')!).track, { id: 'b', name: 'Bass' });

  const wire = JSON.stringify([live, dead, rangeEntry]);
  assert.ok(!/blob:|audioBlob|[A-Za-z]:\\/.test(wire), 'context entries stay id-only too');
}

console.log('assistantReferenceStore: ok');
